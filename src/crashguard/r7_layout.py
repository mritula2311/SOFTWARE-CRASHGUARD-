    if "## Round 7 (V18)" in t:
        t = t[: t.index("## Round 7 (V18)")].rstrip("\n") + "\n"
    lines = t.split("\n")
    out = []
    for ln in lines:
        if ln.startswith("| all |"):
            out.append("| V18 | {} | {} | {} | {} | {} | {} |".format(*(int(R[f"r7.ledger.V18.{k}"]) for k in ("preregistered", "run", "supported", "not_supported", "partly", "not_run"))))
