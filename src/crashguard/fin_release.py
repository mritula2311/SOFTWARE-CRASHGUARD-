"""E: release/crashguard-journal-v1.zip (code, docs, results tables and figures, hashes, the synthetic 5,000-pulse file, VZCrash-derived artefacts with their licence notes). Raw third-party data, processed data derived from them,
literature PDFs and the hardware folder are excluded. Writes HASHES.sha256 inside the archive and docs/05_data_code/RELEASE_MANIFEST.md."""
from __future__ import annotations

import hashlib
import zipfile
from pathlib import Path

OUT = Path("release/crashguard-journal-v1.zip")
INCLUDE_DIRS = ["src", "tests", "scripts", "crashclip", "merge", "docs", "results", "paper", "release/vzcrash_audit_for_authors", "release/synthetic_pulses"]
INCLUDE_FILES = ["Makefile", "requirements.txt", "requirements.lock", "README.md", "LICENSE", "NOTICE", "CITATION.cff", "CITATION.md", ".zenodo.json", "CLAUDE.md"]
EXCLUDE_PARTS = {"__pycache__", ".pytest_cache", "literature", "hardware", "dummy"}
EXCLUDE_SUFFIX = {".pyc", ".log"}


def files() -> list[Path]:
    out = []
    for d in INCLUDE_DIRS:
        for p in sorted(Path(d).rglob("*")):
            if p.is_file() and not (set(p.parts) & EXCLUDE_PARTS) and p.suffix not in EXCLUDE_SUFFIX:
                out.append(p)
    out += [Path(f) for f in INCLUDE_FILES if Path(f).exists()]
    return out


def main() -> None:
    fs = [p for p in files() if p != OUT]
    h = {}
    for p in fs:
        h[p.as_posix()] = hashlib.sha256(p.read_bytes()).hexdigest()
    man = "\n".join(f"{v}  {k}" for k, v in sorted(h.items())) + "\n"
    OUT.parent.mkdir(exist_ok=True)
    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for p in fs:
            z.write(p, p.as_posix())
        z.writestr("HASHES.sha256", man)
    top = {}
    for k in h:
        top[k.split("/")[0]] = top.get(k.split("/")[0], 0) + 1
    doc = ["# Release manifest (generated by `crashguard.fin_release`)", "", f"Archive `release/crashguard-journal-v1.zip`: {len(fs)} files; SHA-256 of every file in `HASHES.sha256` inside the archive. The archive itself is not committed (size); its hash:", "", f"`{hashlib.sha256(OUT.read_bytes()).hexdigest()}`", "",
           "Included: code (Apache-2.0), documents, `results/` (results.json, tables, figures, synthetic pulse parameters, surrogate parameters), `paper/`, the audit package for the VZCrash authors (CC BY-NC 4.0), the 5,000-pulse synthetic file (`release/synthetic_pulses/*.npz`, 2 kHz waveforms).",
           "Excluded: `data/` (raw and processed third-party data; hardware logs), `docs/literature/` (copyright), logs, caches.", "", "Files per top-level folder: " + ", ".join(f"{k} {v}" for k, v in sorted(top.items())) + "."]
    Path("docs/05_data_code/RELEASE_MANIFEST.md").write_text("\n".join(doc) + "\n", encoding="utf-8")
    print(len(fs), "files", round(OUT.stat().st_size / 1e6, 1), "MB")


if __name__ == "__main__":
    main()
