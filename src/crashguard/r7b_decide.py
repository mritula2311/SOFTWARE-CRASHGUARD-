"""Round 7b: decisions of V19 (Holm over two hypotheses) and the results document docs/03_results/ROUND7B_RESULTS.md. Keys r7b.decide.*.

    python -m crashguard.r7b_decide
"""
from __future__ import annotations

import json
from pathlib import Path

from crashguard.results import record_many

ROOT = Path(__file__).resolve().parents[2]
T = ROOT / "results" / "tables"
SRC = "src/crashguard/r7b_decide.py"
ALPHA = 0.05
HEAD = """# Round 7b results: the four-event reserve on fresh seeds

<!-- header:start -->
| Field | Value |
|---|---|
| Status | current |
| Date | 2026-11-16 |
| Owner | Mritula S |
| Scope | Verdicts of V19 (H-R7b-1, H-R7b-2), the bounded formal check of the reserve for k follow-up events and the descriptive trade-off against k. |
| Evidence labels used | SIMULATED, TRACE_DRIVEN, FORMAL, ANALYTICAL |
| Abbreviations | ACK = acknowledgement frame; SF = spreading factor (LoRa) |
<!-- header:end -->

Generated by `python -m crashguard.r7b_decide` from `results/tables/r7b_*.json` and `results/results.json` (keys `r7b.*`). Hypotheses as written in `docs/02_preregistration/PREREGISTRATION_V19.md`. The reserve size k = 4 was chosen from round-7 data (V19 section 0): this is a confirmation on fresh seeds, not a blind test.

"""


def pct(x):
    return f"{100 * x:.1f}%"


def main() -> None:
    att = json.loads((T / "r7b_attack_cells.json").read_text(encoding="utf-8"))
    tr = json.loads((T / "r7b_trace_cells.json").read_text(encoding="utf-8"))
    fm = json.loads((T / "r7b_formal.json").read_text(encoding="utf-8"))
    R = {e["name"]: e["value"] for e in json.loads((ROOT / "results" / "results.json").read_text(encoding="utf-8"))}
    r4 = [c for c in att if c["label"] == "res4" and c["feasible"]]
    p1 = max(c["p_ge_099"] for c in r4)
    lo1 = min(c["lo95"] for c in r4)
    met1 = lo1 >= 0.99
    p2 = float(R["r7b.a2.hR7b_2.p"])
    met2 = bool(R["r7b.a2.hR7b_2.criterion_met"])
    fam = sorted([("H-R7b-1", p1, met1), ("H-R7b-2", p2, met2)], key=lambda x: x[1])
    holm_ok, rej = {}, True
    for i, (n, p, met) in enumerate(fam):
        rej = rej and (p <= ALPHA / (len(fam) - i))
        holm_ok[n] = bool(rej and met)
    ent = []

    def add(name, v, unit, note="", origin="ANALYTICAL"):
        ent.append(dict(name=f"r7b.decide.{name}", value=v, unit=unit, origin=origin, source_file=SRC, notes=note))

    add("hR7b_1.p", p1, "p-value", "worst feasible cell, unrounded")
    add("hR7b_1.supported", int(holm_ok["H-R7b-1"]), "flag", "criterion met and Holm rejection (family of 2, alpha 0.05)")
    add("hR7b_2.p", p2, "p-value")
    add("hR7b_2.supported", int(holm_ok["H-R7b-2"]), "flag", "criterion met and Holm rejection")
    add("family_size", 2, "hypotheses")

    # formal verdicts
    S = {k: R[k] for k in R if k.startswith("r7b.formal.summary.")}
    f1 = S["r7b.formal.summary.m1.inv1_violations_total"] == 0 and S["r7b.formal.summary.m4.inv1_violations_total"] == 0
    f2 = S["r7b.formal.summary.m1.inv2_conditional_violations_total"] == 0 and S["r7b.formal.summary.m4.inv2_conditional_violations_total"] == 0
    f3 = S["r7b.formal.summary.m4.unconditional_violations_n_le_3"] == 0
    f4_stated = sum(c["by_n"][str(n)]["inv2_unconditional"] for c in fm if c["policy"] == "reserved" and c["m"] == 1 and c["model"] == "H" for n in range(4)) > 0
    f4_at4 = any(c["by_n"]["4"]["inv2_unconditional"] > 0 for c in fm if c["policy"] == "reserved" and c["m"] == 1 and c["model"] == "H") and all(c["by_n"]["4"]["inv2_unconditional"] == 0 for c in fm if c["policy"] == "reserved" and c["m"] == 4 and c["model"] == "H" and c["B"] == 40)
    add("formal.F1_inv1_zero", int(f1), "flag", origin="FORMAL")
    add("formal.F2_inv2_conditional_zero", int(f2), "flag", origin="FORMAL")
    add("formal.F3_m4_no_violation_n_le_3", int(f3), "flag", origin="FORMAL")
    add("formal.F4_stated_m1_violates_n_le_3", int(f4_stated), "flag", "as written in V19: NOT met if 0", origin="FORMAL")
    add("formal.F4_observed_m1_violates_at_n4_m4_does_not_at_B40", int(f4_at4), "flag", "what the control shows instead: at 4 earlier events and B = 40 the m = 1 policy violates, the m = 4 policy does not", origin="FORMAL")
    add("formal.m1_first_violation_n", S["r7b.formal.summary.m1.min_n_unconditional_violation"], "earlier events", origin="FORMAL")
    add("formal.m4_first_violation_n", S["r7b.formal.summary.m4.min_n_unconditional_violation"], "earlier events", "expected 4 in V19; observed 5", origin="FORMAL")
    record_many(ent, purge_prefixes=("r7b.decide.",))

    L = [HEAD]
    L.append("## 1. Verdicts (Holm over two hypotheses, alpha = 0.05)\n")
    L.append("| Hypothesis | Criterion | Result | p | Verdict |")
    L.append("|---|---|---|---:|---|")
    L.append(f"| H-R7b-1 (SIMULATED) | k = 4 policy: follow-up on time in at least 99% of runs, lower 95% limit, every feasible cell (9 cells, 1,200 runs each, seeds 100 to 105) | worst lower limit {pct(lo1)}; rate at least {pct(min(c['rate'] for c in r4))} in every cell | {p1:.2e} | {'SUPPORTED' if holm_ok['H-R7b-1'] else 'NOT SUPPORTED'} |")
    nf = int(R["r7b.a2.cells_failing_delivery"])
    L.append(f"| H-R7b-2 (TRACE_DRIVEN) | k = 4 policy against old, no attack: delivery -1 point at most and median time +10% at most, every cell (18 cells, trace seed 4242) | delivery fails in {nf} of 18 cells, time in {int(R['r7b.a2.cells_failing_time'])} | {p2:.3g} | {'SUPPORTED' if holm_ok['H-R7b-2'] else 'NOT SUPPORTED'} |\n")
    L.append("## 2. H-R7b-1 cells (fresh seeds, q = 1, primary stress)\n")
    L.append("| Duty model | SF | n earlier events | old | k = 1 | k = 2 | k = 3 | k = 4 | k = 4 lower 95% limit | median delay k = 4 (s) |")
    L.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for m in ("H1", "H10", "T10"):
        for sf in (7, 8, 9):
            cs = {c["label"]: c for c in att if c["model"] == m and c["sf"] == sf}
            L.append(f"| {m} | {sf} | {cs['old']['n_prior']} | " + " | ".join(pct(cs[x]["rate"]) for x in ("old", "res1", "res2", "res3", "res4")) + f" | {pct(cs['res4']['lo95'])} | {cs['res4']['delay_median']:.3f} |")
    L.append("\nThe k = 1 column reproduces the V18 failure at the 1% allowance (H1: 70%, 27%, 35% in round 7) on fresh seeds. India's 10% rules are the main deployment regime (H10 and T10 rows); 1% (H1) is the stricter case. k = 2 and k = 3 are DESCRIPTIVE.\n")
    L.append("## 3. H-R7b-2: benign cost on the trace cells\n")
    L.append("Cells that fail the criterion (delivery difference, k = 4 minus old, lower 95% limit below -0.01):\n")
    L.append("| Group | Scheme | Duty model | delivery difference | lower 95% limit | median-time ratio | upper 95% limit |")
    L.append("|---|---|---|---:|---:|---:|---:|")
    for k, v in sorted(tr.items()):
        g, s, m, p = k.split(".")
        if p == "res4" and v["lo95"] < -0.01:
            L.append(f"| {g} | {s} | {m} | {100 * v['delivery_diff']:.2f} points | {100 * v['lo95']:.2f} points | {v['ratio']:.3f} | {v['ratio_hi95']:.3f} |")
    L.append("\n**Trade-off of benign delivery against k (DESCRIPTIVE, group H, scheme R3, delivery difference against old in points; the other scheme and the other groups are in `results/tables/r7b_trace_cells.json`):**\n")
    L.append("| Duty model | k = 1 | k = 2 | k = 3 | k = 4 |")
    L.append("|---|---:|---:|---:|---:|")
    for m in ("H1", "H10", "T10"):
        L.append(f"| {m} | " + " | ".join(f"{100 * tr[f'H.R3.{m}.res{i}']['delivery_diff']:.2f}" for i in (1, 2, 3, 4)) + " |")
    L.append("\nThe curve is flat: the replay runs each start point as an isolated event with a fresh duty state, so the size of the reserve does not bind, and the cost comes from the withdrawal rule (a flash that cannot finish before the follow-up is due is not sent) and, under the off-time, from the time guard, which does not depend on k. A benign cost that grows with k would appear only under sustained load; that case was not run (NOT_RUN).\n")
    L.append("## 4. Formal check (FORMAL, bounded)\n")
    L.append(f"Bounds (V19 section 3): {R['r7b.formal.bounds.text']}.\n")
    L.append("| Check | Statement | Result |")
    L.append("|---|---|---|")
    L.append(f"| F1 | Invariant 1, no class-L frame leaves less than R | {'holds, 0 violations' if f1 else 'FAILS'} |")
    L.append(f"| F2 | Invariant 2, reserve intact at pending, up to 5 earlier events | {'holds, 0 violations' if f2 else 'FAILS'} |")
    L.append(f"| F3 | k = 4 policy, unconditional Invariant 2, at most 3 earlier events | {'holds, 0 violations' if f3 else 'FAILS'} |")
    L.append(f"| F4 as written | k = 1 policy violates unconditional Invariant 2 with at most 3 earlier events | {'met' if f4_stated else 'NOT met: 0 violations with at most 3 earlier events'} |")
    L.append(f"| F4 observed | at 4 earlier events and B = 40: k = 1 violates, k = 4 does not | {'yes' if f4_at4 else 'no'} |")
    L.append("\nPer B (unconditional violations by the number of earlier events n; counts are weighted by the number of attacker choices that reach each state):\n")
    L.append("| Model | B | policy | n = 3 | n = 4 | n = 5 | smallest n with a violation |")
    L.append("|---|---:|---|---:|---:|---:|---:|")
    for c in fm:
        nm = {0: "old", 1: "k = 1", 4: "k = 4"}[c["m"]] if c["policy"] == "reserved" else "old"
        vs = [n for n in range(6) if c["by_n"][str(n)]["inv2_unconditional"] > 0]
        L.append(f"| {c['model']} | {c['B'] or '-'} | {nm} | " + " | ".join(str(c["by_n"][str(n)]["inv2_unconditional"]) for n in (3, 4, 5)) + f" | {vs[0] if vs else 'none'} |")
    L.append("\nReading. The k = 4 policy keeps the follow-up on time through four earlier events at B = 40 and through five at B = 48; the k = 1 policy fails at four earlier events at B = 40. The old policy fails under the off-time from the start (T). Limits of the abstraction: the window of 70 steps holds about four events, so the old policy and the k = 1 policy do not fail before four earlier events, which is why control F4 as written (at most 3 earlier events) is not met; the distinction between the policies appears at the bound of four. The smallest violating n of the k = 4 policy is at 5 earlier events (V19 expected 4). The check is for the model, not for the radio.\n")
    (ROOT / "docs" / "03_results" / "ROUND7B_RESULTS.md").write_text(HEAD and "\n".join(L), encoding="utf-8")
    print({e["name"]: e["value"] for e in ent})


if __name__ == "__main__":
    main()
