"""Write docs/01_protocol/ATTACK_CASES.md from results/tables/attacks.csv and results.json, and fill count markers in hand-written docs.

The case count is never typed in a document: it is read from ``attacks.cases_total`` in results.json. Hand-written files that need the number use the marker
``<!--n:attacks.cases_total-->48<!--/n-->``; ``fill_markers`` rewrites the text between the tags.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pandas as pd

from crashguard import config as C

R = Path("results/results.json")
OUT = Path("docs/01_protocol/ATTACK_CASES.md")
MARK = re.compile(r"<!--n:([\w.\-]+)-->(.*?)<!--/n-->", re.S)


def _res() -> dict:
    return {e["name"]: e for e in json.loads(R.read_text(encoding="utf-8"))}


def _cell(s: object) -> str:
    return str(s).replace("|", "/").replace("\n", " ")


CATEGORIES = [("flood", "flood and duty cycle"), ("Limit on", "flood and duty cycle"), ("reboot", "reboot and counter persistence"), ("Spoofed ACK", "ACK attacks"), ("Old ACK", "ACK attacks"), ("Genuine ACK", "ACK attacks"),
              ("presented as an ACK", "ACK attacks"), ("single-bit flip", "tag forgery and tampering"), ("Forged", "tag forgery and tampering"), ("wrong key", "tag forgery and tampering"), ("Tampered", "tag forgery and tampering"),
              ("Counter exhausted", "documented limits"), ("another node_id", "documented limits"), ("Replay", "replay, retry and counter"), ("retries", "replay, retry and counter"), ("Old counter", "replay, retry and counter"),
              ("Same counter", "replay, retry and counter"), ("Strict verifier", "replay, retry and counter"), ("fresh counter", "replay, retry and counter"), ("re-ACK", "replay, retry and counter"),
              ("length", "format and length"), ("Wrong", "format and length"), ("All-zero", "format and length"), ("All-ones", "format and length"), ("Truncated", "format and length"), ("reflection", "format and length"),
              ("Valid alert", "valid alert and fields"), ("Delta-V", "valid alert and fields"), ("does not advance", "tag forgery and tampering")]


def category_of(name: str) -> str:
    for key, cat in CATEGORIES:
        if key.lower() in name.lower():
            return cat
    return "other"


def render_categories(df: pd.DataFrame) -> list[str]:
    cats: dict[str, list[int]] = {}
    for i, row in enumerate(df.itertuples()):
        cats.setdefault(category_of(str(row.case)), []).append(i)
    out = ["", "## The original cases by category", "", "| Category | Cases | Ids | As expected |", "|---|---|---|---|"]
    for c, ids in sorted(cats.items()):
        ok = int(df.match.iloc[ids].sum())
        out.append(f"| {c} | {len(ids)} | {', '.join(f'{i:02d}' for i in ids)} | {ok} |")
    return out


def render_extra(extra: pd.DataFrame | None) -> list[str]:
    if extra is None or not len(extra):
        return []
    out = ["", "## Additional designed test cases (T11)", "",
           f"{len(extra)} additional designed test cases written after the original cases, with the expected outcome fixed before the run; {int(extra.match.sum())} behave as expected. These are DESIGNED TEST CASES, not independent attackers, and they are counted separately from the original cases above "
           "(`attacks_x.*` in `results.json`). Where the expected outcome documents a known weakness (X06, X07) the case is expected to show it.", "",
           "| Id | Description | Category | Expected | Observed | Origin | Note |", "|---|---|---|---|---|---|---|"]
    out += [f"| {r.id} | {_cell(r.case)} | {r.category} | {_cell(r.expected)} | {_cell(r.observed)} | SIMULATED | {_cell(r.note if isinstance(r.note, str) else '')} |" for r in extra.itertuples()]
    return out


def render(df: pd.DataFrame, r: dict, extra: pd.DataFrame | None = None) -> str:
    total, ok = r["attacks.cases_total"]["value"], r["attacks.cases_matching_expected"]["value"]
    origin = r["attacks.cases_total"]["origin"]
    lines = [
        "# Attack cases",
        "",
        "Generated by `python -m crashguard.attack_doc` from `results/tables/attacks.csv` and `results/results.json`. Do not edit by hand.",
        "",
        f"**Count (from `attacks.cases_total`): {total} cases, {ok} behave as expected.** Origin of every row: {origin} (a software simulation of the reference verifier and the node's ACK check; not a measurement on the radios). "
        "Every other document takes this count from `results.json`; `tests/test_consistency.py` fails if a document states a different number.",
        "",
        "| Id | Description | Expected | Observed | Origin | Note |",
        "|---|---|---|---|---|---|",
    ]
    for i, row in enumerate(df.itertuples()):
        note = row.note if isinstance(row.note, str) else ""
        lines.append(f"| {i:02d} | {_cell(row.case)} | {_cell(row.expected)} | {_cell(row.observed)} | {origin} | {_cell(note)} |")
    lines += render_categories(df) + render_extra(extra)
    return "\n".join(lines) + "\n"


def fill_markers(path: Path, r: dict) -> bool:
    """Replace the text inside every ``<!--n:key-->..<!--/n-->`` marker with the value of ``key``. Returns True if the file changed."""
    s = path.read_text(encoding="utf-8")

    def sub(m: re.Match) -> str:
        e = r.get(m.group(1))
        return f"<!--n:{m.group(1)}-->{e['value'] if e else 'NOT_RUN'}<!--/n-->"

    t = MARK.sub(sub, s)
    if t != s:
        path.write_text(t, encoding="utf-8")
    return t != s


def main() -> None:
    r = _res()
    df = pd.read_csv(C.TABLES / "attacks.csv")
    assert len(df) == r["attacks.cases_total"]["value"], "attacks.csv and results.json disagree"
    ex = C.TABLES / "attacks_extra.csv"
    OUT.write_text(render(df, r, pd.read_csv(ex) if ex.exists() else None), encoding="utf-8")
    changed = [str(p) for p in list(Path("docs").rglob("*.md")) + [Path("README.md")] if "archive" not in p.parts and fill_markers(p, r)]
    print(f"wrote {OUT} ({len(df)} cases); markers updated in: {changed}")


if __name__ == "__main__":
    main()
