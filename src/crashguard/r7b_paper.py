"""Round 7b: LaTeX macros (paper/generated/numbers_r7b.tex) from results/results.json keys r7b.*.

    python -m crashguard.r7b_paper

A missing key stops the run. Macro names start with Rsevb.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "paper" / "generated" / "numbers_r7b.tex"
SFN = {7: "Seven", 8: "Eight", 9: "Nine"}


def load() -> dict:
    return {e["name"]: e["value"] for e in json.loads((ROOT / "results" / "results.json").read_text(encoding="utf-8"))}


def fmt(kind: str, v) -> str:
    v = float(v)
    return {"d1": f"{v:.1f}", "d2": f"{v:.2f}", "d3": f"{v:.3f}", "i": f"{int(round(v)):d}", "pct": f"{100 * v:.1f}", "pct0": f"{100 * v:.0f}",
            "e": f"{v:.2e}".replace("e-0", "e-").replace("e+0", "e+"), "ms": f"{1000 * v:.1f}", "ppabs": f"{abs(100 * v):.1f}", "ppabs2": f"{abs(100 * v):.2f}", "pct2": f"{100 * v:.2f}"}[kind]


def spec(R: dict) -> list[tuple[str, str]]:
    S: list[tuple[str, str]] = []

    def add(name: str, key: str, kind: str) -> None:
        assert key in R, key
        S.append((name, fmt(kind, R[key])))

    add("RsevbPowerMaxDipole", "r7b.g0.power.max_compliant_ptx_dipole_dbm", "i")
    add("RsevbPowerExtraDb", "r7b.g0.power.extra_margin_db", "d2")
    add("RsevbPowerSfSteps", "r7b.g0.power.extra_margin_sf_steps", "d1")
    add("RsevbCollFour", "r7b.g5.pseudonym.collision_L4", "e")
    add("RsevbCollFive", "r7b.g5.pseudonym.collision_L5", "e")
    for sf, n in SFN.items():
        add(f"RsevbExtraByteAck{n}", f"r7b.g5.pseudonym.sf{sf}.b26.extra_ms", "d2")
        add(f"RsevbExtraByteAlert{n}", f"r7b.g5.pseudonym.sf{sf}.b97.extra_ms", "d2")
        add(f"RsevbExtraByteFlash{n}", f"r7b.g5.pseudonym.sf{sf}.b14.extra_ms", "d2")
    for sf, n in SFN.items():
        add(f"RsevbOneRateSf{n}", f"r7b.a1.sim.H1.sf{sf}.res1.rate", "pct")
        add(f"RsevbOldRateSf{n}", f"r7b.a1.sim.H1.sf{sf}.old.rate", "pct")
        add(f"RsevbTwoRateSf{n}", f"r7b.a1.sim.H1.sf{sf}.res2.rate", "pct")
        add(f"RsevbThreeRateSf{n}", f"r7b.a1.sim.H1.sf{sf}.res3.rate", "pct")
        add(f"RsevbFourRateSf{n}", f"r7b.a1.sim.H1.sf{sf}.res4.rate", "pct")
    add("RsevbWorstLower", "r7b.a1.sim.hR7b_1.worst_lower_limit", "pct2")
    add("RsevbPOne", "r7b.decide.hR7b_1.p", "e")
    add("RsevbCellsFeasible", "r7b.a1.sim.hR7b_1.n_feasible_cells", "i")
    add("RsevbBenignFailCells", "r7b.a2.cells_failing_delivery", "i")
    add("RsevbBenignCells", "r7b.a2.n_cells", "i")
    add("RsevbBenignHTenDelta", "r7b.a2.H.R3.T10.res4.delivery_diff", "ppabs2")
    add("RsevbBenignHHourDelta", "r7b.a2.H.R3.H1.res4.delivery_diff", "ppabs2")
    add("RsevbFormMOneFirst", "r7b.formal.summary.m1.min_n_unconditional_violation", "i")
    add("RsevbFormMFourFirst", "r7b.formal.summary.m4.min_n_unconditional_violation", "i")
    add("RsevbFormMFourInv", "r7b.formal.summary.m4.inv2_conditional_violations_total", "i")
    add("RsevbFormMFourInvOne", "r7b.formal.summary.m4.inv1_violations_total", "i")
    add("RsevbFormOldCond", "r7b.formal.summary.old.inv2_conditional_violations_total", "i")
    add("RsevcAtomicFiles", "r7c.atomic.files_scanned", "i")  # round 7c key, written by scripts/r7c_atomic_scan.py
    if "r7d.reack.budget.duty" in R:  # round 7d keys, written by crashguard.r7d_base
        add("RsevdIntervalSeven", "r7d.reack.interval_s.sf7", "d2")
        add("RsevdIntervalEight", "r7d.reack.interval_s.sf8", "d2")
        add("RsevdIntervalNine", "r7d.reack.interval_s.sf9", "d2")
        add("RsevdDutyPct", "r7d.reack.budget.duty", "pct0")
        add("RsevdCapacity", "r7d.reack.budget.capacity_s", "i")
        add("RsevdInitial", "r7d.reack.budget.initial_s_in_flood_study", "i")
        add("RsevdRate", "attacks.flood.rate_per_s", "i")
        add("RsevdDuration", "attacks.flood.duration_s", "i")
        add("RsevdOffReacks", "r7d.reack.flood.off.reacks", "i")
        add("RsevdOffAirtime", "r7d.reack.flood.off.airtime_s", "d1")
        add("RsevdOffRefused", "r7d.reack.flood.off.refused_no_budget", "i")
        add("RsevdOnReacks", "r7d.reack.flood.on.reacks", "i")
        add("RsevdOnAirtime", "r7d.reack.flood.on.airtime_s", "d1")
        add("RsevdOnShare", "r7d.reack.flood.on.share_of_initial_budget_spent", "pct0")
    add("RsevbRebootScanMs", "r7b.g5.reboot.scan_s_stored", "ms")
    add("RsevbRebootEntries", "r7b.g5.reboot.table_entries", "i")
    add("RsevbRebootBytes", "r7b.g5.reboot.table_bytes", "i")
    for k in sorted(R):
        if k.startswith("r7b.v19.macro."):
            S.append(("Rsevb" + k.split(".")[-1], str(R[k])))
    return S


def main() -> None:
    R = load()
    lines = ["% generated by crashguard.r7b_paper from results/results.json (keys r7b.*); do not edit"]
    for n, v in spec(R):
        lines.append(f"\\newcommand{{\\{n}}}{{{v}}}")
    if "r7b.ledger.all.preregistered" in R:
        for nm, key in (("LedgerN", "preregistered"), ("LedgerRun", "run"), ("LedgerSupp", "supported"), ("LedgerNot", "not_supported"), ("LedgerPartly", "partly"), ("LedgerNotRun", "not_run"),
                        ("LedgerConfN", "confirmatory_rows"), ("LedgerConfSupp", "confirmatory_supported"), ("LedgerVersions", "versions")):
            lines.append(f"\\renewcommand{{\\{nm}}}{{{int(R[f'r7b.ledger.all.{key}'])}}}")
        for sfx, key in (("Pre", "preregistered"), ("Run", "run"), ("Supp", "supported"), ("Not", "not_supported"), ("Partly", "partly"), ("NotRun", "not_run")):
            lines.append(f"\\newcommand{{\\LgH{sfx}}}{{{int(R[f'r7b.ledger.V19.{key}'])}}}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(len(lines) - 1, "macros")


if __name__ == "__main__":
    main()
