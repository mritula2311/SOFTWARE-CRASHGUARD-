"""X2 (N18): severity measures against the dummy injury criteria recorded in the NHTSA crash tests (docs/02_preregistration/EXPERIMENTS_EXTRA.md, written before this was run).

The criteria are in the occupant records of the NHTSA metadata (cached in data/raw/nhtsa/meta_<test>.json). Field meanings are from the NHTSA Biomechanics Data Reference
Guide, version 4.b, volume II (opened): HIC (with the time interval T1 to T2 in ms), CLIP3M (peak 3 ms chest acceleration, g), LFEM and RFEM (peak femur compression, newtons,
negative), CSI, TTI(d), PELVG (peak lateral pelvis acceleration, g). Dummy criteria are test measurements, not human injury; the sample is small.
Limits (opened): FMVSS 208 S6 (HIC15 700, chest 60 g except 3 ms, femur 2250 pounds = 10,008 N), FMVSS 214 (HIC over a 36 ms interval at most 1000 for the ES-2re; the old
SID limits for TTI(d) and pelvis are NOT in the current text and are UNVERIFIED, so no share against them is computed).
"""
from __future__ import annotations

import json

import numpy as np
import pandas as pd
from scipy.stats import rankdata

from crashguard import boot as B
from crashguard import config as C
from crashguard import nhtsa as N

MIN_N = 20  # a cell with fewer tests is not analysed
N_FEMUR_LIMIT = 10_008.0  # 2250 pounds in newtons (FMVSS 208 S6.5)
LIMITS = {"frontal": (("hic", "HIC (15 ms interval) above 700", 700.0, True), ("clip3m", "chest acceleration (3 ms clip) above 60 g", 60.0, False), ("femur", "femur compression above 10,008 N", N_FEMUR_LIMIT, False)),
          "side": (("hic", "HIC (36 ms interval) above 1000", 1000.0, False),)}
SEVERITY = {"dv": "delta-V", "asi": "ASI", "peakp": "peak pulse acceleration", "energy": "specific energy"}
CHAINS = {"orig": "reference chain (original rate, unclipped)", "hz100_r16": "+-16 g, 100 Hz", "hz100_r64": "+-64 g, 100 Hz"}
POSITIONS = {"01": "front seat on the struck side (driver)", "02": "front passenger", "04": "rear seat"}


def criteria_table(tests_meta: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for t in tests_meta.itertuples():
        m = json.loads((N.RAW / f"meta_{t.test_no}.json").read_text(encoding="utf-8"))
        for o in m.get("OCCUPANT", []):
            def val(k):
                v = o.get(k)
                return float(v) if v not in (None,) else np.nan

            lf, rf = val("LFEM"), val("RFEM")
            rows.append(dict(test_no=t.test_no, kind=t.kind, group_mm=t.group_mm, group=t.group, speed=t.speed, loc=str(o.get("OCCLOC")), dummy=str(o.get("OCCTYPD")),
                             hic=val("HIC"), hic_window_ms=val("T2") - val("T1"), clip3m=val("CLIP3M"), femur=np.nanmax([abs(lf), abs(rf)]) if not (np.isnan(lf) and np.isnan(rf)) else np.nan,
                             csi=val("CSI"), tti=val("TTI"), pelvg=val("PELVG")))
    d = pd.DataFrame(rows)
    for c in ("hic", "clip3m", "femur", "csi", "tti", "pelvg"):
        d[c] = d[c].where(d[c] > 0)  # a recorded zero means the criterion was not computed for that dummy position
    return d


def severity_table() -> pd.DataFrame:
    s = pd.read_csv(C.TABLES / "nhtsa_tests.csv")
    out = pd.DataFrame(dict(test_no=s.test_no, kind=s.kind, speed=s.impact_speed_kmh, make=s.make, model=s.model, year=s.year, cls=s.class_orig))
    out["group_mm"] = out.make.astype(str) + "|" + out.model.astype(str)
    out["group"] = out.group_mm + "|" + out.year.astype(str)
    for ch in CHAINS:
        out[f"dv_{ch}"], out[f"asi_{ch}"], out[f"peakp_{ch}"] = s[f"dv_{ch}"], s[f"asi_{ch}"], s[f"peakp_{ch}"]
        out[f"energy_{ch}"] = 0.5 * (s[f"dv_{ch}"] / 3.6) ** 2  # J per kg
    return out


def spearman(x: np.ndarray, y: np.ndarray) -> float:
    rx, ry = rankdata(x), rankdata(y)
    if rx.std() == 0 or ry.std() == 0:
        return float("nan")
    return float(np.corrcoef(rx, ry)[0, 1])


def partial_spearman(x: np.ndarray, y: np.ndarray, z: np.ndarray) -> float:
    """Rank-based partial correlation of x and y controlling for z."""
    rx, ry, rz = rankdata(x), rankdata(y), rankdata(z)
    if rz.std() == 0:
        return spearman(x, y)
    def resid(a):
        b = np.polyfit(rz, a, 1)
        return a - np.polyval(b, rz)
    ex, ey = resid(rx), resid(ry)
    if ex.std() == 0 or ey.std() == 0:
        return float("nan")
    return float(np.corrcoef(ex, ey)[0, 1])


def write_dataset_block(crit: pd.DataFrame, path=None) -> None:
    """Record in docs/05_data_code/DATASET.md which tests have which dummy criteria (between markers)."""
    from pathlib import Path

    path = Path(path or "docs/05_data_code/DATASET.md")
    names = {"hic": "HIC (interval T2 - T1 in the data)", "clip3m": "chest peak 3 ms (g)", "femur": "femur compression (N)", "csi": "CSI", "tti": "TTI(d)", "pelvg": "pelvis peak lateral (g)"}
    lines = ["<!-- injury:start -->", "", "### NHTSA dummy injury criteria used in X2 (generated by `python -m crashguard.injury`)", "",
             "Source: the `OCCUPANT` records of the NHTSA test metadata (public domain). Field meanings: NHTSA Biomechanics Data Reference Guide, version 4.b, volume II (opened). A recorded zero is treated as 'not computed'. "
             "A criterion is analysed only where at least 20 tests have it. Test numbers per cell:", ""]
    for kind in ("frontal", "side"):
        for loc in ("01", "02", "04"):
            for c, nm in names.items():
                g = crit[(crit.kind == kind) & (crit["loc"] == loc) & crit[c].notna()]
                if len(g) >= MIN_N:
                    lines.append(f"- {kind}, position {loc}, {nm}: {len(g)} tests: " + ", ".join(str(int(x)) for x in sorted(g.test_no.unique())))
    lines += ["", "<!-- injury:end -->"]
    blk = "\n".join(lines)
    doc = path.read_text(encoding="utf-8")
    if "<!-- injury:start -->" in doc:
        import re

        doc = re.sub(r"<!-- injury:start -->.*?<!-- injury:end -->", lambda m: blk, doc, flags=re.S)
    else:
        doc = doc.rstrip("\n") + "\n\n" + blk + "\n"
    path.write_text(doc, encoding="utf-8")


def _stat(f):
    return lambda a: f(a[:, 0], a[:, 1], a[:, 2]) if a.shape[1] == 3 else f(a[:, 0], a[:, 1])


def main() -> None:
    from crashguard.results import record_many

    sev = severity_table()
    sev["test_no"] = sev.test_no.astype(int)
    meta = sev[["test_no", "kind", "speed", "group", "group_mm"]]
    crit = criteria_table(meta)
    C.TABLES.mkdir(parents=True, exist_ok=True)
    crit.to_csv(C.TABLES / "x2_criteria.csv", index=False)
    ent: list[dict] = []
    src = "results/tables/x2_correlations.csv"

    def add(name, value, unit, origin="MEASURED_SOFTWARE", notes="", s=src):
        ent.append(dict(name=f"x2.{name}", value=value, unit=unit, origin=origin, source_file=s, notes=notes))

    # availability: which tests have which criteria
    avail = []
    for kind in ("frontal", "side"):
        k = crit[crit.kind == kind]
        for loc in sorted(k["loc"].unique()):
            g = k[k["loc"] == loc]
            for c in ("hic", "clip3m", "femur", "csi", "tti", "pelvg"):
                n = int(g[c].notna().sum())
                if n:
                    avail.append(dict(kind=kind, position=loc, criterion=c, tests=n))
                    add(f"avail.{kind}.pos{loc}.{c}", n, "tests", s="results/tables/x2_criteria.csv")
    pd.DataFrame(avail).to_csv(C.TABLES / "x2_availability.csv", index=False)
    write_dataset_block(crit)
    rows = []
    for kind in ("frontal", "side"):
        for loc in ("01", "02", "04"):
            for crit_name in ("hic", "clip3m", "femur", "csi", "tti", "pelvg"):
                cc = crit[(crit.kind == kind) & (crit["loc"] == loc)][["test_no", crit_name, "group_mm", "speed"]].dropna(subset=[crit_name])
                if len(cc) < MIN_N:
                    continue
                d = cc.merge(sev.drop(columns=["speed", "group_mm", "kind"]), on="test_no")
                cluster = d.group_mm.to_numpy()
                for ch in CHAINS:
                    for sv in SEVERITY:
                        x = d[f"{sv}_{ch}"].to_numpy(float)
                        y = d[crit_name].to_numpy(float)
                        z = d.speed.to_numpy(float)
                        ok = np.isfinite(x) & np.isfinite(y) & np.isfinite(z)
                        if ok.sum() < MIN_N:
                            continue
                        arr = np.stack([x[ok], y[ok], z[ok]], axis=1)
                        grp = cluster[ok]
                        rho = B.ci_grouped(arr, grp, lambda a: spearman(a[:, 0], a[:, 1]))
                        par = B.ci_grouped(arr, grp, lambda a: partial_spearman(a[:, 0], a[:, 1], a[:, 2]))
                        rows.append(dict(kind=kind, position=loc, criterion=crit_name, chain=ch, severity=sv, n=int(ok.sum()), n_groups=len(set(grp.tolist())), rho=rho[0], rho_lo=rho[1], rho_hi=rho[2],
                                         partial=par[0], partial_lo=par[1], partial_hi=par[2]))
                # speed alone against the criterion, and delta-V against speed
                x = d["speed"].to_numpy(float)
                y = d[crit_name].to_numpy(float)
                ok = np.isfinite(x) & np.isfinite(y)
                rs = B.ci_grouped(np.stack([x[ok], y[ok]], axis=1), cluster[ok], lambda a: spearman(a[:, 0], a[:, 1]))
                rows.append(dict(kind=kind, position=loc, criterion=crit_name, chain="speed", severity="speed", n=int(ok.sum()), n_groups=len(set(cluster[ok].tolist())), rho=rs[0], rho_lo=rs[1], rho_hi=rs[2],
                                 partial=np.nan, partial_lo=np.nan, partial_hi=np.nan))
    R = pd.DataFrame(rows)
    R.to_csv(C.TABLES / "x2_correlations.csv", index=False)
    if len(R) == 0:
        add("run", "NOT_RUN", "text", origin="NOT_RUN", notes="no dummy criteria available for any cell")
        record_many(ent, purge_prefixes=("x2.",))
        return
    for r_ in R.itertuples():
        nm = f"{r_.kind}.pos{r_.position}.{r_.criterion}.{r_.chain}.{r_.severity}"
        add(f"{nm}.n", int(r_.n), "tests")
        add(f"{nm}.rho", round(float(r_.rho), 4), "correlation")
        add(f"{nm}.rho_lo", round(float(r_.rho_lo), 4), "correlation")
        add(f"{nm}.rho_hi", round(float(r_.rho_hi), 4), "correlation")
        if r_.severity != "speed":
            add(f"{nm}.partial", round(float(r_.partial), 4), "correlation", notes="rank-based partial correlation controlling for impact speed")
            add(f"{nm}.partial_lo", round(float(r_.partial_lo), 4), "correlation")
            add(f"{nm}.partial_hi", round(float(r_.partial_hi), 4), "correlation")
    # delta-V against impact speed alone
    for kind in ("frontal", "side"):
        d = sev[sev.kind == kind]
        for ch in CHAINS:
            x, y = d[f"dv_{ch}"].to_numpy(float), d.speed.to_numpy(float)
            ok = np.isfinite(x) & np.isfinite(y)
            p = B.ci_grouped(np.stack([x[ok], y[ok]], axis=1), d.group_mm.to_numpy()[ok], lambda a: spearman(a[:, 0], a[:, 1]))
            add(f"{kind}.dv_vs_speed.{ch}.rho", round(p[0], 4), "correlation")
            add(f"{kind}.dv_vs_speed.{ch}.rho_lo", round(p[1], 4), "correlation")
            add(f"{kind}.dv_vs_speed.{ch}.rho_hi", round(p[2], 4), "correlation")
            add(f"{kind}.dv_vs_speed.{ch}.n", int(ok.sum()), "tests")
    # classes against regulatory limits (reference chain classes)
    share_rows = []
    for kind, lims in LIMITS.items():
        for crit_name, label, limit, need_15 in lims:
            cc = crit[(crit.kind == kind) & (crit["loc"] == "01")][["test_no", crit_name, "hic_window_ms"]].dropna(subset=[crit_name])
            if need_15:
                cc = cc[cc.hic_window_ms <= 15.5]
            d = cc.merge(sev[["test_no", "cls", "group_mm"]], on="test_no")
            if len(d) < MIN_N:
                add(f"limit.{kind}.{crit_name}.n", int(len(d)), "tests", notes="too few tests with a verified interval")
                continue
            add(f"limit.{kind}.{crit_name}.n", int(len(d)), "tests", notes=label)
            add(f"limit.{kind}.{crit_name}.share_exceeding_all", round(float((d[crit_name] > limit).mean()), 4), "fraction", notes=label)
            for k in range(4):
                g = d[d.cls == k]
                if len(g) >= 5:
                    p = B.ci_grouped((g[crit_name] > limit).astype(float).to_numpy(), g.group_mm.to_numpy(), np.mean)
                    add(f"limit.{kind}.{crit_name}.class{k}.share", round(p[0], 4), "fraction", notes=label)
                    add(f"limit.{kind}.{crit_name}.class{k}.share_lo", round(p[1], 4), "fraction")
                    add(f"limit.{kind}.{crit_name}.class{k}.share_hi", round(p[2], 4), "fraction")
                add(f"limit.{kind}.{crit_name}.class{k}.n", int(len(g)), "tests")
                share_rows.append(dict(kind=kind, criterion=crit_name, severity_class=k, n=int(len(g)), share_exceeding=float((g[crit_name] > limit).mean()) if len(g) else np.nan))
    pd.DataFrame(share_rows).to_csv(C.TABLES / "x2_limits.csv", index=False)
    add("limit.tti_pelvg.status", "UNVERIFIED", "text", origin="NOT_RUN", notes="TTI(d) and pelvis limits of the old SID dummy are not in the current FMVSS 214 text that was opened; no share against them is computed")
    add("hic.share_window_le_15ms.frontal", round(float((crit[(crit.kind == "frontal")].hic_window_ms <= 15.5).mean()), 4), "fraction", notes="share of frontal dummy records whose HIC interval T2 - T1 is at most 15.5 ms")
    record_many(ent, purge_prefixes=("x2.",))
    # decision cells
    prim = R[(R.kind == "frontal") & (R.position == "01") & (R.criterion.isin(["clip3m", "hic"])) & (R.chain == "orig") & (R.severity.isin(["dv", "asi"]))]
    pd.set_option("display.width", 220)
    print(prim[["criterion", "severity", "n", "rho", "rho_lo", "rho_hi", "partial", "partial_lo", "partial_hi"]].round(3).to_string())
    print(R[(R.chain == "orig") & (R.severity.isin(["dv", "speed"])) & (R.position == "01")][["kind", "criterion", "severity", "n", "rho", "rho_lo", "rho_hi", "partial", "partial_lo", "partial_hi"]].round(3).to_string())


if __name__ == "__main__":
    main()
