"""Round 6 decision table: Holm over the seven hypotheses of PREREGISTRATION_V17 (formal rows p = 1e-300 if proved, else 1), keys r6.holm.*, and docs/03_results/ROUND6_RESULTS.md.

    python -m crashguard.r6_decide
"""
from __future__ import annotations

import json
from pathlib import Path

from crashguard.results import record_many

ROOT = Path(__file__).resolve().parents[2]
SRC = "src/crashguard/r6_decide.py"


def holm(ps: list[float]) -> list[float]:
    m = len(ps)
    order = sorted(range(m), key=lambda i: ps[i])
    out = [0.0] * m
    run = 0.0
    for rank, i in enumerate(order):
        run = max(run, (m - rank) * ps[i])
        out[i] = min(1.0, run)
    return out


def main() -> None:
    R = {e["name"]: e["value"] for e in json.loads((ROOT / "results" / "results.json").read_text(encoding="utf-8"))}

    def formal(flag):
        return (1e-300 if int(R[flag]) == 1 else 1.0), int(R[flag]) == 1

    rows = []  # id, text, met, p, label
    rows.append(("H-R6-1a", "micro-confirm extra airtime at SF9 at most 0.40 in 8 ns-3 cells", int(R["r6.r1.hR6_1a.criterion_met"]) == 1, float(R["r6.r1.hR6_1a.p"]), "SIMULATED"))
    rows.append(("H-R6-1b", "micro-confirm delivery not lower than R3 by more than 0.01 in 16 ns-3 cells and 3 trace groups", int(R["r6.r1.hR6_1b.criterion_met"]) == 1, float(R["r6.r1.hR6_1b.p"]), "SIMULATED and TRACE_DRIVEN"))
    p, met = formal("r6.f.h1c.criterion_met")
    rows.append(("H-R6-1c", "binding, anti-replay and cancel lemmas hold and the control model is attacked", met, p, "FORMAL"))
    rows.append(("H-R6-2a", "sequential early exit at least 200 ms earlier (mean, lower 95% limit)", int(R["r6.r2.hR6_2a.criterion_met"]) == 1, float(R["r6.r2.hR6_2a.p"]), "MEASURED_SOFTWARE"))
    rows.append(("H-R6-2b", "retraction share rises by at most 0.02 (upper 95% limit)", int(R["r6.r2.hR6_2b.criterion_met"]) == 1, float(R["r6.r2.hR6_2b.p"]), "MEASURED_SOFTWARE"))
    p, met = formal("r6.f.h3a.criterion_met")
    rows.append(("H-R6-3a", "forward secrecy of the hash ratchet within 3 steps", met, p, "FORMAL"))
    p, met = formal("r6.f.h3b.criterion_met")
    rows.append(("H-R6-3b", "quarantine cannot be triggered by unverified frames (variant B proved; variant A attacked)", met, p, "FORMAL"))
    adj = holm([r[3] for r in rows])
    ent = []

    def add(name, v, unit, note, origin="ANALYTICAL"):
        ent.append(dict(name=f"r6.holm.{name}", value=v, unit=unit, origin=origin, source_file=SRC, notes=note))

    sup = 0
    for (hid, _t, met, p, lab), a in zip(rows, adj):
        ok = bool(met and a < 0.05)
        sup += ok
        k = hid.lower().replace("-", "")
        add(f"{k}.p", p, "p-value", "raw p-value (count + 1) / 2,001, or 1e-300 for a proved FORMAL hypothesis, 1 otherwise")
        add(f"{k}.p_holm", round(a, 6), "p-value", "Holm over the seven hypotheses of V17")
        add(f"{k}.verdict", "SUPPORTED" if ok else "NOT SUPPORTED", "verdict", "criterion met and Holm p below 0.05")
    add("n_supported", int(sup), "of 7", "")
    record_many(ent, purge_prefixes=("r6.holm.",))
    f = lambda k, nd=3: f"{float(R[k]):.{nd}f}"  # noqa: E731
    L = ["# Round 6: results and decision table", "", "<!-- header:start -->", "<!-- header:end -->", "",
         "Generated by `python -m crashguard.r6_decide` from `results/results.json` (keys `r6.*`). Design: `docs/02_preregistration/PREREGISTRATION_V17.md`, committed before any development run. "
         "Every number has an origin label; ns-3 results are SIMULATED, trace results TRACE_DRIVEN, prover results FORMAL (symbolic models), bounds ANALYTICAL, build sizes MEASURED_SOFTWARE (build artifacts).", "",
         "## 1. Decision table (Holm over seven)", "", "| Hypothesis | Statement | Label | Criterion met | Raw p | Holm p | Verdict |", "|---|---|---|---|---:|---:|---|"]
    for (hid, t, met, p, lab), a in zip(rows, adj):
        L.append(f"| {hid} | {t} | {lab} | {int(met)} | {p:.4g} | {a:.4g} | {'SUPPORTED' if met and a < 0.05 else 'NOT SUPPORTED'} |")
    L += ["", f"{sup} of 7 supported. Total over all rounds: see `docs/04_audits/HYPOTHESIS_LEDGER.md` ({int(R['r6.ledger.all.preregistered'])} hypotheses in {int(R['r6.ledger.all.versions'])} versions; V17 adds seven). "
          "The kill criterion of R6-1 (H-R6-1a or H-R6-1c fails) was not triggered; that of R6-2 (H-R6-2a not supported) was.", "",
          "## 2. What each part shows", "",
          f"- **R6-1 micro-confirm** (`ROUND6_R1_MICRO.md`). ns-3 airtime is {min(float(R[f'r6.r1.ns3.sf{sf}.{st}.p{p}.air_over_r3']) for sf in (7, 9) for st in ('calib', 'shipped') for p in ('0', '0.1', '0.3', '0.6')):.2f} to "
          f"{max(float(R[f'r6.r1.ns3.sf{sf}.{st}.p{p}.air_over_r3']) for sf in (7, 9) for st in ('calib', 'shipped') for p in ('0', '0.1', '0.3', '0.6')):.2f} of R3's with delivery within 0.003. The extra-airtime test against single-stage is nearly automatic. "
          "The frame has 13 bytes in ns-3 (design: 7) and the trace delivery test is zero by construction. The micro-confirm gives up the content of the full confirm.",
          "- **R6-1c, R6-3 formal** (`formal/`, `formal/out/r6/`). ProVerif and Tamarin prove the binding, anti-replay and cancel lemmas of the micro-confirm; the control model whose tag omits T1 is attacked in both. "
          f"The hash ratchet gives authenticity and secrecy of past alerts within a bound of {int(R['r6.f.h3a.ratchet_steps_bound'])} ratchet steps (the bound is part of the result). The bounded quarantine model finds an attack on the count-before-verification rule "
          f"({int(R['r6.f3b.A_count_before_verification.shortest_attack_frames'])} frames from a vehicle without any key); the count-after-verification rule holds by construction (frames that fail verification do not reach the counters), so the content of H-R6-3b is the attack on the other rule and the fix.",
          f"- **R6-2 sequential exit** (`ROUND6_R2_SEQUENTIAL.md`). Mean time gain {f('r6.r2.hR6_2.a_pt', 1)} ms (lower limit {f('r6.r2.hR6_2.a_lo', 1)} ms); retraction share +{f('r6.r2.hR6_2.b_pt')} (upper limit {f('r6.r2.hR6_2.b_hi')}). Not supported; a regime boundary: "
          "the fixed rule already decides at the earliest checkpoint for most events.",
          f"- **R6-4 footprint** (`ROUND6_FOOTPRINT.md`). Forest data {int(R['r6.fp.rodata.forest_bytes']):,} bytes; linked flash {int(R['r6.fp.image.flash_total_bytes']):,} bytes (unused functions included); micro-confirm check stack chain "
          f"{int(R['r6.fp.stack.micro_verify_chain_bytes'])} bytes (static sum). Emulator counts and energy NOT_RUN (no emulator).",
          f"- **R6-5, R6-7 bounds and propositions** (`ROUND6_BOUNDS.md`, ANALYTICAL). Exact airtime and attempt bounds, the extra-airtime lower bound ({f('r6.b.extra.sf7.r3_lower_bound')} at SF7, {f('r6.b.extra.sf9.r3_lower_bound')} at SF9), a greedy-retry proposition with proof, the spreading-factor rule, and the quarantine indexing finding.", ""]
    (ROOT / "docs" / "03_results" / "ROUND6_RESULTS.md").write_text("\n".join(L), encoding="utf-8")
    print({r[0]: ("SUPPORTED" if r[2] and a < 0.05 else "NOT SUPPORTED") for r, a in zip(rows, adj)})


if __name__ == "__main__":
    main()
