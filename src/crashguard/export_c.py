"""Export a scikit-learn random forest to plain C and check it against Python (S6).

The header has const arrays only, no heap. Thresholds are stored as the largest float32 not above the
sklearn float64 threshold, so ``x <= thr`` on a float32 feature gives the same branch as sklearn.
"""
from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

import joblib
import numpy as np

from crashguard import config as C
from crashguard.results import record_many

HEADER = Path("firmware_export/crashguard_rf.h")
SKETCH = Path("firmware_export/benchmark_rf.ino")


def _f32_floor(x: float) -> np.float32:
    t = np.float32(x)
    return np.nextafter(t, np.float32(-np.inf)) if float(t) > x else t


def forest_arrays(model) -> dict:
    feat, thr, left, right, roots = [], [], [], [], []
    for est in model.estimators_:
        t = est.tree_
        base = len(feat)
        roots.append(base)
        for i in range(t.node_count):
            if t.children_left[i] == -1:
                v = t.value[i, 0]
                feat.append(-1)
                thr.append(np.float32(v[1] / v.sum()))
                left.append(0)
                right.append(0)
            else:
                feat.append(int(t.feature[i]))
                thr.append(_f32_floor(float(t.threshold[i])))
                left.append(base + int(t.children_left[i]))
                right.append(base + int(t.children_right[i]))
    return dict(feat=feat, thr=thr, left=left, right=right, roots=roots)


def _fl(x) -> str:
    return repr(float(np.float32(x))) + "f"


def write_header(model, path: Path = HEADER, thr_f1: float | None = None, n_features: int = len(C.FEATURES)) -> dict:
    a = forest_arrays(model)
    n = len(a["feat"])
    assert n < 65535
    idx = "int16_t" if n < 32767 else "uint16_t"  # same 2 bytes per index; only the sign differs
    join = ", ".join
    lines = [
        "/* Generated by crashguard.export_c. Do not edit. Feature order = docs/05_data_code/FEATURES.md. */",
        "#ifndef CRASHGUARD_RF_H", "#define CRASHGUARD_RF_H", "#include <stdint.h>", "",
        f"#define CG_N_FEATURES {n_features}", f"#define CG_N_TREES {len(a['roots'])}", f"#define CG_N_NODES {n}",
    ]
    if thr_f1 is not None:
        lines.append(f"#define CG_THRESHOLD {_fl(thr_f1)} /* chosen on the validation split */")
    lines += [
        "",
        "/* feature index, or -1 for a leaf (then thr holds the crash probability of the leaf) */",
        f"static const int8_t cg_feat[CG_N_NODES] = {{{join(map(str, a['feat']))}}};",
        f"static const float cg_thr[CG_N_NODES] = {{{join(map(_fl, a['thr']))}}};",
        f"static const {idx} cg_left[CG_N_NODES] = {{{join(map(str, a['left']))}}};",
        f"static const {idx} cg_right[CG_N_NODES] = {{{join(map(str, a['right']))}}};",
        f"static const {idx} cg_root[CG_N_TREES] = {{{join(map(str, a['roots']))}}};",
        "",
        "static inline float predict_prob(const float f[CG_N_FEATURES]) {",
        "    float acc = 0.0f;",
        "    for (int t = 0; t < CG_N_TREES; t++) {",
        "        int n = cg_root[t];",
        "        while (cg_feat[n] >= 0) n = (f[cg_feat[n]] <= cg_thr[n]) ? cg_left[n] : cg_right[n];",
        "        acc += cg_thr[n];",
        "    }",
        "    return acc / (float)CG_N_TREES;",
        "}", "", "#endif", "",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return dict(nodes=n, trees=len(a["roots"]), bytes_est=n * C.NODE_BYTES)


def find_compiler() -> list[str] | None:
    for c in ("gcc", "cc", "clang"):
        if shutil.which(c):
            return [c]
    try:
        out = subprocess.run([sys.executable, "-m", "ziglang", "version"], capture_output=True, text=True)
        if out.returncode == 0:
            return [sys.executable, "-m", "ziglang", "cc"]
    except OSError:
        pass
    return None


HARNESS = r"""
#include <stdio.h>
#include <stdlib.h>
#include "crashguard_rf.h"
int main(int argc, char **argv) {
    FILE *in = fopen(argv[1], "rb"); FILE *out = fopen(argv[2], "wb");
    float f[CG_N_FEATURES];
    while (fread(f, sizeof(float), CG_N_FEATURES, in) == CG_N_FEATURES) {
        float p = predict_prob(f);
        fwrite(&p, sizeof(float), 1, out);
    }
    fclose(in); fclose(out); return 0;
}
"""


def c_predict(header: Path, X: np.ndarray, tag: str = "rf_check") -> tuple[np.ndarray, str]:
    """Compile the header with a C compiler and run it on X (float32, n x n_features). Returns (probs, compiler).

    The check is built into build/<tag>.exe and run up to 5 times with growing waits (``cbuild``); if Windows Application Control still blocks it,
    ``cbuild.BlockedError`` (a RuntimeError) is raised and the caller records NOT_RUN with the reason.
    """
    from crashguard import cbuild

    BUILD = cbuild.BUILD
    BUILD.mkdir(parents=True, exist_ok=True)
    np.ascontiguousarray(X, np.float32).tofile(BUILD / f"{tag}_in.bin")
    out = BUILD / f"{tag}_out.bin"
    if out.exists():
        out.unlink()  # never reuse an output of an earlier run
    cc = cbuild.compile_and_run(tag, HARNESS, header.parent, [BUILD / f"{tag}_in.bin", out])
    return np.fromfile(out, np.float32), cc


def mirror_entries(header: Path, X: np.ndarray, py: np.ndarray, thr: float, prefix: str) -> list[dict]:
    """Independent pure-Python check of the header (float32, same order of arithmetic as the C code) against scikit-learn."""
    from crashguard.c_mirror import rf_mirror

    m = rf_mirror(header, X)
    diff = float(np.abs(m.astype(np.float64) - py).max())
    src = str(header)
    return [dict(name=f"{prefix}.mirror_max_abs_diff", value=diff, unit="probability", origin="MEASURED_SOFTWARE", source_file=src,
                 notes="pure-Python float32 mirror of predict_prob, read from the generated header text, against scikit-learn predict_proba; independent of the C compiler"),
            dict(name=f"{prefix}.mirror_decision_agreement", value=float(((m >= thr) == (py >= thr)).mean()), unit="fraction", origin="MEASURED_SOFTWARE", source_file=src),
            dict(name=f"{prefix}.mirror_rows", value=int(len(X)), unit="events", origin="MEASURED_SOFTWARE", source_file=src)]


def write_sketch(X: np.ndarray, path: Path = SKETCH, n: int = 8) -> None:
    k = min(n, len(X))
    rows = ",\n".join("  {" + ", ".join(_fl(v) for v in x) + "}" for x in X[:k])
    path.write_text(
        "// Benchmark for the exported random forest. BUILT, NOT YET MEASURED on an ESP32.\n"
        "// Feature vectors are real triggered test events from VZCrash (CC BY-NC 4.0).\n"
        '#include "crashguard_rf.h"\n\n'
        f"static const float SAMPLES[{k}][CG_N_FEATURES] = {{\n{rows}\n}};\n\n"
        "void setup() {\n"
        "  Serial.begin(115200);\n"
        "  delay(500);\n"
        "  volatile float sink = 0.0f;\n"
        "  const int CALLS = 1000;\n"
        "  uint32_t t0 = micros();\n"
        f"  for (int i = 0; i < CALLS; i++) sink += predict_prob(SAMPLES[i % {k}]);\n"
        "  uint32_t dt = micros() - t0;\n"
        '  Serial.printf("predict_prob: %d calls, %lu us total, %.2f us per call (sink %f)\\n",\n'
        "                CALLS, (unsigned long)dt, dt / (float)CALLS, (double)sink);\n"
        "}\n\n"
        "void loop() {}\n",
        encoding="utf-8",
    )


def main() -> None:
    from crashguard.models import PRIMARY, frames

    bundle = joblib.load(C.PROCESSED / "rf15_seed42.joblib")
    model = bundle["model"]
    info = write_header(model, thr_f1=bundle["thr_f1"])
    _, _, te = frames(PRIMARY)
    te = te[te.triggered]
    X = te[list(C.FEATURES)].to_numpy(np.float32)
    py = model.predict_proba(X)[:, 1]
    src = str(HEADER)
    ent = [
        dict(name="export.nodes_total", value=info["nodes"], unit="nodes", origin="MEASURED_SOFTWARE", source_file=src, notes="15 trees, depth 6, seed 42"),
        dict(name="export.bytes_est", value=info["bytes_est"], unit="bytes", origin="ANALYTICAL", source_file=src,
             notes=f"nodes x {C.NODE_BYTES} bytes (int8 + float32 + 2 x int16); host estimate, not an ESP32 compile report"),
        dict(name="export.test_rows", value=int(len(X)), unit="events", origin="MEASURED_SOFTWARE", source_file=src, notes="triggered test events"),
        dict(name="export.benchmark_us_per_call", value="NOT_RUN", unit="us", origin="NOT_RUN", source_file=str(SKETCH),
             notes="needs the ESP32; sketch is built, not yet measured"),
    ]
    try:
        c, cc = c_predict(HEADER, X)
        diff = float(np.abs(c.astype(np.float64) - py).max())
        agree = float(((c >= bundle["thr_f1"]) == (py >= bundle["thr_f1"])).mean())
        ent += [
            dict(name="export.max_abs_diff", value=diff, unit="probability", origin="MEASURED_SOFTWARE", source_file=src,
                 notes=f"C (compiled with {cc}) against scikit-learn predict_proba on the full triggered test set"),
            dict(name="export.decision_agreement", value=agree, unit="fraction", origin="MEASURED_SOFTWARE", source_file=src,
                 notes="same crash / not-crash decision at the validation threshold"),
            dict(name="export.equivalence_passes", value=bool(diff <= 1e-6), unit="bool", origin="MEASURED_SOFTWARE", source_file=src, notes="threshold 1e-6"),
        ]
        print(f"max abs diff {diff:.3e}, decision agreement {agree:.6f}, compiler {cc}")
    except RuntimeError as err:
        ent.append(dict(name="export.max_abs_diff", value="NOT_RUN", unit="probability", origin="NOT_RUN", source_file=src,
                        notes=f"compiled C check could not run: {str(err)[:150]}; the Python mirror check below was run instead"))
    ent += mirror_entries(HEADER, X, py, bundle["thr_f1"], "export")
    record_many(ent, purge_prefixes=("export.",))
    write_sketch(X)


if __name__ == "__main__":
    main()
