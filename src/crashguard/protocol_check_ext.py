"""T12: bounded check extension for the flash message and for CANCEL after a delayed ACK (ANALYTICAL; a check of the MODEL, not of the implementation). TLC was NOT_RUN.

Bounds EXT: counters up to 4, one event, 3 alert sends, 1 flash send, one CANCEL send, 3 attacker actions (replay, injected invalid-tag message, spoofed ACK), 1 lost message, 3 messages in flight per direction,
no reboots. Messages may be delivered in any order and ACKs may arrive after the CANCEL. Variants: the design (a CANCEL for a counter the base has not seen is refused) and the fix (such a CANCEL is remembered).
New properties: C3 a CANCEL that was delivered is never lost because it arrived before its alert; C4 a late valid ACK never restarts sending after CANCEL; F1 an ACK of the flash never ends the alert retries.
The results are appended to docs/01_protocol/PROTOCOL_MODEL.md between markers.
"""
from __future__ import annotations

import time
from pathlib import Path

from crashguard import protocol_model_ext as M

DOC = Path("docs/01_protocol/PROTOCOL_MODEL.md")
START, END = "<!-- ext:start -->", "<!-- ext:end -->"
SRC = "src/crashguard/protocol_model_ext.py"
EXT = M.Bounds(cmax=4, max_events=1, max_tries=3, max_flash=1, max_att=3, max_loss=1, max_inflight=3, max_reboot_base=0, max_reboot_car=0)
RUNS = [("design", M.Variant("design")), ("keep_pending_cancel", M.Variant("keep_pending_cancel", keep_pending_cancel=True))]
SHOW = ("S1_replay_or_forgery_accepted_as_new", "S2_spoofed_ack_stops_retries", "S3_repeat_not_acked_or_budget_exceeded", "S4_accepted_counters_not_increasing", "C1_cancel_without_valid_signature",
        "C2_send_after_valid_ack", "C3_cancel_lost_by_reordering", "C4_late_ack_restarts_sending", "F1_flash_ack_stops_alert_retries")


def main() -> None:
    from crashguard.results import record_many

    ent: list[dict] = []
    lines = [START, "", "## 8. Extension T12: the flash message and CANCEL after a delayed ACK (ANALYTICAL; generated by `python -m crashguard.protocol_check_ext`)", "",
             "Bounds EXT: counters up to 4, one event, 3 alert sends, 1 flash send, one CANCEL send, 3 attacker actions, 1 lost message, 3 messages in flight, no reboots; delivery in any order, ACKs may arrive after the CANCEL. "
             "This checks the model, not the implementation.", "", "| Variant | States | Depth | " + " | ".join(p.split("_")[0] for p in SHOW) + " |", "|---|---|---|" + "---|" * len(SHOW)]
    traces = []
    for nm, v in RUNS:
        t = time.time()
        r = M.explore(v, EXT)
        cells = []
        for p in SHOW:
            pr = r["props"][p]
            ok = pr["holds"]
            cells.append("holds" if ok else f"**FAILS** ({len(pr['trace'])} steps)")
            ent.append(dict(name=f"s12x.EXT.{nm}.{p}", value=int(ok), unit="flag", origin="ANALYTICAL", source_file=SRC, notes="1 = holds within the bounds; 0 = a counterexample exists (docs/01_protocol/PROTOCOL_MODEL.md section 8)"))
            if not ok:
                traces.append(f"**{nm} / {p}** (shortest counterexample, {len(pr['trace'])} steps):\n" + "\n".join(f"{k + 1}. {s}" for k, s in enumerate(pr["trace"])))
        ent.append(dict(name=f"s12x.EXT.{nm}.states", value=r["states"], unit="states", origin="ANALYTICAL", source_file=SRC, notes="reachable states, level-by-level search, complete"))
        ent.append(dict(name=f"s12x.EXT.{nm}.depth", value=r["depth"], unit="steps", origin="ANALYTICAL", source_file=SRC, notes=""))
        lines.append(f"| {nm} | {r['states']:,} | {r['depth']} | " + " | ".join(cells) + " |")
        print(nm, r["states"], round(time.time() - t), cells)
    lines += ["", "Property names: C3 a delivered CANCEL is lost when it arrives before its alert; C4 a late valid ACK restarts sending after CANCEL; F1 an ACK of the flash ends the alert retries. 'holds' = no counterexample within the bounds.", "",
              "### Counterexamples", ""] + traces + ["", "The design refuses a CANCEL for a counter it has not seen; if the CANCEL overtakes its alert (reordering), the alert is accepted afterwards and the event stays active although the driver cancelled (attack-suite case X06 shows the same behaviour in the reference code). "
              "The fix (remember such a CANCEL) removes it within the bounds. Not changed in the reference code or the firmware in this round.", END]
    text = DOC.read_text(encoding="utf-8")
    block = "\n".join(lines)
    text = (text[: text.index(START)] + block + text[text.index(END) + len(END):]) if START in text else text.rstrip("\n") + "\n\n" + block + "\n"
    DOC.write_text(text, encoding="utf-8")
    record_many(ent, purge_prefixes=("s12x.",))


if __name__ == "__main__":
    main()
