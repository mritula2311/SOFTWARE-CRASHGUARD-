"""Write docs/03_results/SIMHW_VARIANTS.md: every variant of the simulated hardware-format logs with seed, change and SHA-256 (generated).

    python -m crashguard.sh_variants        # regenerates nothing; reads data/simulated_hardware/variants (make them with python -m crashguard.hwsim_v2)
"""
from __future__ import annotations

import json
from pathlib import Path

from crashguard import hwsim_v2 as H
from crashguard import sh_load as L

OUT = Path("docs/03_results/SIMHW_VARIANTS.md")
CHANGE = {
    "V00_base": "100 Hz, no tilt, noise x1, bias sd 0.03 g, crash peak median 5 g, link as `hwsim.py`; correct by construction (axes of the repository rule)",
    "T_x15": "mounting tilt 15 degrees about x", "T_x30": "mounting tilt 30 degrees about x", "T_y15": "mounting tilt 15 degrees about y", "T_y30": "mounting tilt 30 degrees about y",
    "F_x": "sign of the x axis flipped", "F_y": "sign of the y axis flipped", "S_10Hz": "10 Hz sampling", "S_jit1": "timestamp jitter, sd 1 ms (100 Hz)",
    "S_drop05": "0.5% of the samples dropped (100 Hz)", "N_x2": "noise x2", "N_x4": "noise x4", "B_08": "bias sd 0.08 g", "P_3": "crash peak median 3 g", "P_8": "crash peak median 8 g",
    "L_0": "added per-direction loss 0%", "L_10": "added per-direction loss 10%", "L_30": "added per-direction loss 30%", "I_block": "interferer blocking 5 s in 10% of the minutes",
}


def main() -> None:
    hashes = json.loads((H.OUTDIR / "VARIANT_HASHES.json").read_text(encoding="utf-8"))
    rows = []
    for i, name, _p, kind in H.VARIANTS:
        meta = json.loads((H.OUTDIR / name / "variant.json").read_text(encoding="utf-8"))
        nfiles = len(list((H.OUTDIR / name).rglob("*.json")))
        rows.append(f"| {i} | {name} | {meta['seed']} | {kind} | {CHANGE[name]} | {meta['n_sensor_events']} | {nfiles} | `{hashes[name]}` |")
    sens = json.loads((H.OUTDIR / "SW_SENS_HASHES.json").read_text(encoding="utf-8")) if (H.OUTDIR / "SW_SENS_HASHES.json").exists() else {}
    man = dict(L.manifest())
    L_ = ["# Variants of the simulated hardware-format logs", "", "<!-- header:start -->", "<!-- header:end -->", "",
          "Generated by `python -m crashguard.sh_variants`. The files are SIMULATED by `src/crashguard/hwsim_v2.py` (evidence label SIMULATED_HW_FORMAT) and are never hardware evidence. "
          "The variants and seeds were fixed in `docs/02_preregistration/PREREGISTRATION_V11.md` before any test ran; no variant was added or removed afterwards. Seed of variant i = 20261114 + 1000 i. "
          "The variant files are not committed (they are about 40 MB); rebuild them with `python -m crashguard.hwsim_v2` and compare the hashes below (the hash is the SHA-256 over the relative path and the SHA-256 of every `.json` file of the variant).", "",
          "| i | Variant | Seed | Kind | Change from the base | Sensor events | JSON files | SHA-256 |", "|---|---|---|---|---|---|---|---|", *rows, "",
          "Sensor variants (0 to 14) hold 100 crash events (20 per side: front, rear, left, right, vertical) and 100 non-crash events (20 per kind: hand tap, hard braking, lift and place, ramp bump, rough driving). "
          "Radio variants (0 and 15 to 18) hold the eight link runs (10, 50, 100 m, 100 m behind a wall, 30, 34, 38, 42 dB) with 100 packets each and 100 end-to-end events.", "",
          "## S5 sensitivity sets (SW-420 threshold ranges 0.8 to 2.0 g and 3.0 to 6.0 g)", "",
          "Requested for S5 and generated with the same seed as each sensor variant, so the IMU data are identical to the variant's and only the six SW-420 channels differ. They are not part of the 19 variants.", "",
          "| Set | SHA-256 |", "|---|---|", *[f"| {k} | `{v}` |" for k, v in sens.items()], "",
          "## The supplied set (`data/simulated_hardware/`, `hwsim.py`, seed 20261114)", "",
          f"{sum(1 for k in man if k.startswith('sensor_logs/'))} sensor logs, {sum(1 for k in man if k.startswith('protocol_logs/'))} protocol logs; the SHA-256 of every file is in `data/simulated_hardware/MANIFEST.sha256`.", ""]
    OUT.write_text("\n".join(L_), encoding="utf-8")
    print("written", OUT)


if __name__ == "__main__":
    main()
