"""A3: docs/07_log/NOT_RUN.md. Lists every NOT_RUN entry of results/results.json (grouped by reason) and every source that could not be opened (from docs/06_references/REFERENCES.md and docs/06_references/NOVELTY_SCAN.md). Generated; no value is typed."""
from __future__ import annotations

from crashguard.textutil import clip

import json
import re
from collections import defaultdict
from pathlib import Path


def main() -> None:
    R = json.loads(Path("results/results.json").read_text(encoding="utf-8"))
    nr = [e for e in R if e["origin"] == "NOT_RUN"]
    groups: dict[str, list[str]] = defaultdict(list)
    for e in nr:
        why = clip(re.sub(r"\d+", "#", str(e["notes"])), 140)
        groups[why].append(e["name"])
    lines = ["# NOT_RUN items and sources that could not be opened (generated by `crashguard.fin_a3`)", "",
             f"Read from `results/results.json` ({len(R)} entries, {len(nr)} with origin NOT_RUN). Entries that share a reason are grouped; the full notes are in `results/results.json`. Hardware items (`hw.*`) wait for the author's logs in `data/hardware/` (not read here).", "",
             "## NOT_RUN entries", "", "| Reason (digits masked) | Count | Example keys |", "|---|---|---|"]
    for why, names in sorted(groups.items(), key=lambda kv: -len(kv[1])):
        lines.append(f"| {why.replace('|', '/')} | {len(names)} | {', '.join('`' + n + '`' for n in names[:3])}{' ...' if len(names) > 3 else ''} |")
    lines += ["", "## Other items not done (no results.json entry)", "",
              "- TLC (the model checker) was not available: the protocol model is checked by an explicit-state search in Python (`crashguard.protocol_check`), which checks the model within its bounds, not the implementation.",
              "- ESP32 timing, flash and RAM measurements, and microcontroller cross-compilation (no cross compiler or emlearn here).",
              "- India duty-cycle limit (WPC/DoT): UNVERIFIED; the simulator takes the limit as a parameter (1% by default; 0.1% in block G).",
              "- Regulatory status of listen-before-talk on 433 MHz: UNVERIFIED.",
              "- A second public vehicle-pulse dataset (T13) and an external delta-V severity scale (T6): candidates could not be opened.",
              "- IEEE Xplore and Scopus searches (not reachable); strings are in `docs/06_references/MANUAL_SEARCH_CHECKLIST.md`.", "",
              "## Sources that could not be opened (not cited for any number)", "",
              "- Jao and Shkel 2022 (triangular-function reconstruction with Gaussian-process regression): searches on 2026-11-11 and 2026-11-12 did not return it.",
              "- Zhang et al. 2026 (peak-aware saturation compensation): same.",
              "- Wusk and Gabler, 25th ESV, paper 25-0407: only a search listing of a TRID record was seen; the page could not be fetched.",
              "- Carvalho et al. 2021 and Chen et al. GLOBECOM 2023: could not be opened (`docs/06_references/NOVELTY_SCAN.md`).",
              "- Ruder et al. (spline restoration of clipped tibial signals): known only through Chan et al.",
              "- STMicroelectronics LSM6DSV32X data sheet and page: the ST address timed out.",
              "- nhtsa.gov terms pages: HTTP 403 (the NHTSA terms are therefore not verified; the data.gov entry was opened and its rights field reads \"public\").",
              "- MDPI journal pages: HTTP 403; Europe PMC copies were read where available.",
              "- Wald 1945 (sequential probability ratio test): mentioned, not opened.",
              "- analog.com data sheet pages were not reachable by curl on 2026-11-11 (see `docs/05_data_code/SENSOR_DATASHEETS.md` for what was read and where).", ""]
    Path("docs/07_log/NOT_RUN.md").write_text("\n".join(lines), encoding="utf-8")
    print(len(nr), len(groups))


if __name__ == "__main__":
    main()
