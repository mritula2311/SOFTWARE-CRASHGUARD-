def sat_resources(src: str) -> list[dict]:
    """Host estimates (ANALYTICAL): static RAM of the C code and the size of its object code on the host."""
    import subprocess

    from crashguard.cbuild import BUILD
    from crashguard.export_c import find_compiler

    n = C.WIN_N
    sev_ram = 4 * (3 * n + n + 3 * n + n)  # a[N][3], h[N], ft[3][N], tl[N] of cg_severity
    sat_ram = 4 * (2 * n + n + 3 * n) + n + 4 * 3 * n  # a[N][2], h[N], filled[N][3], sat[N] bytes, and the fill window
    ent = [dict(name="export_severity.n14.ram_static_bytes", value=int(sev_ram + sat_ram), unit="bytes", origin="ANALYTICAL", source_file=src,
                notes="sum of the static arrays of cg_severity and cg_sat_fill for the 280-sample window; a count, not an ESP32 map file"),
           dict(name="export_severity.n14.ram_added_by_n14_bytes", value=int(sat_ram), unit="bytes", origin="ANALYTICAL", source_file=src, notes="static arrays of cg_sat_fill and cg_severity_sat only")]
    cc = find_compiler()
    if cc is None:
        return ent
    try:
        BUILD.mkdir(parents=True, exist_ok=True)
        (BUILD / "size_probe.c").write_text('#include "severity.h"\nint probe(const float a[][3], int n, int t, cgs_sat_result_t *r) { return cg_severity_sat(a, 0, n, t, 100.0f, r); }\n')
        (BUILD / "size_probe_base.c").write_text('#include "severity.h"\nint probe(const float a[][3], int n, int t, cgs_result_t *r) { return cg_severity(a, 0, n, t, 100.0f, r); }\n')
        sizes = {}
        for name in ("size_probe", "size_probe_base"):
            r = subprocess.run([*cc, "-Os", "-c", "-std=c99", f"-I{HEADER.parent.resolve()}", str(BUILD / f"{name}.c"), "-o", str(BUILD / f"{name}.o")], capture_output=True, text=True)
            if r.returncode:
                return ent
            sizes[name] = text_size(BUILD / f"{name}.o")
        ent += [dict(name="export_severity.n14.code_bytes_host", value=int(sizes["size_probe"]), unit="bytes", origin="ANALYTICAL", source_file=src,
                     notes="size of the code sections of the host object file (-Os) with the N14 code; a host estimate, an ESP32 build differs"),
                dict(name="export_severity.n14.code_bytes_host_baseline", value=int(sizes["size_probe_base"]), unit="bytes", origin="ANALYTICAL", source_file=src, notes="same for the baseline severity code alone"),
                dict(name="export_severity.n14.code_bytes_added_host", value=int(sizes["size_probe"] - sizes["size_probe_base"]), unit="bytes", origin="ANALYTICAL", source_file=src)]
    except Exception:
        pass
    return ent


def text_size(path: Path) -> int:
    """Sum of the code section sizes of a COFF or ELF object file (host estimate)."""
    import struct

    b = path.read_bytes()
    if b[:4] == b"\x7fELF":
        shoff = struct.unpack_from("<Q", b, 0x28)[0]
        shentsize, shnum = struct.unpack_from("<H", b, 0x3A)[0], struct.unpack_from("<H", b, 0x3C)[0]
        total = 0
        for i in range(shnum):
            _n, typ, flags, _a, _o, size = struct.unpack_from("<IIQQQQ", b, shoff + i * shentsize)
            if typ == 1 and flags & 4:  # PROGBITS and executable
                total += size
        return total
    nsec = struct.unpack_from("<H", b, 2)[0]
    opt = struct.unpack_from("<H", b, 16)[0]
    total = 0
    for i in range(nsec):
        off = 20 + opt + 40 * i
        name = b[off:off + 8].rstrip(b"\0")
        size = struct.unpack_from("<I", b, off + 16)[0]
        flags = struct.unpack_from("<I", b, off + 36)[0]
        if name.startswith(b".text") or flags & 0x20:
            total += size
    return total


