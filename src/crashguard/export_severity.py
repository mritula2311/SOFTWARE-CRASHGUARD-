def sat_windows() -> tuple[np.ndarray, np.ndarray, dict]:
    """Windows for the N14 check: NHTSA sensor windows at the configured range (MEASURED_SOFTWARE inputs) and clipped synthetic pulses (SIMULATED inputs)."""
    from crashguard import severity_synth as Y
    from crashguard.nhtsa import sensor_windows

    wins, trigs, kind = [], [], []
    try:
        na, _ng = sensor_windows()
        for w in na:
            wins.append(w.astype(np.float32))
            trigs.append(C.PRE_N)
            kind.append("nhtsa")
    except Exception:  # NHTSA not available: only the synthetic windows
        pass
    rng = np.random.default_rng(C.SEED)
    for shp in Y.SHAPES:
        for A in (20.0, 40.0, 80.0, 150.0):
            for T in (0.04, 0.08, 0.12, 0.16):
                acc, trig = Y.make_window(shp, A, T, 0.0, float(C.FS_HZ), rng, clip_g=C.MPU_RANGE_G)
                if trig >= 0:
                    wins.append(acc.astype(np.float32))
                    trigs.append(trig)
                    kind.append("synthetic")
    return np.stack(wins), np.array(trigs), dict(kind=kind)


