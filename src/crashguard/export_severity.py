def c_severity(acc: np.ndarray, gyro: np.ndarray, header: Path = HEADER) -> tuple[np.ndarray, str]:
    """Run the C code on N windows. acc, gyro: (N, WIN_N, 3) float32. Returns (N, 16) outputs and the compiler name.

    Built into build/sev_check.exe and run up to 5 times with growing waits (``cbuild``); a blocked program raises ``cbuild.BlockedError``.
    """
    from crashguard import cbuild

    BUILD = cbuild.BUILD
    BUILD.mkdir(parents=True, exist_ok=True)
    rec = np.concatenate([acc.reshape(len(acc), -1), gyro.reshape(len(gyro), -1)], axis=1).astype(np.float32)
    rec.tofile(BUILD / "sev_check_in.bin")
    out = BUILD / "sev_check_out.bin"
    if out.exists():
        out.unlink()
    cc = cbuild.compile_and_run("sev_check", HARNESS % (C.WIN_N, C.PRE_N), header.parent, [BUILD / "sev_check_in.bin", out])
    return np.fromfile(out, np.float32).reshape(-1, N_OUT), cc


def python_severity(acc: np.ndarray, gyro: np.ndarray) -> np.ndarray:
    out = np.zeros((len(acc), N_OUT))
    for i in range(len(acc)):
        r = S.severity(acc[i].astype(np.float64), C.FS_HZ, C.PRE_N, gyro[i].astype(np.float64))
        out[i] = [r[k] for k in OUT_FIELDS]
    return out


MIRROR_N = 400  # windows per data set for the pure-Python float32 mirror (it is slow: scalar arithmetic)
CHECK_FIELDS = ("dv_res_kmh", "asi", "thiv_kmh", "pulse_ms", "peak_pulse_g", "tilt_deg", "tilt_corrected_deg")


def _unit(name: str) -> str:
    return "km/h" if "kmh" in name else ("ms" if "ms" in name else "degrees" if "deg" in name else "g" if "_g" in name else "index")


def _diff_entries(label: str, who: str, a_out: np.ndarray, b_out: np.ndarray, against: str, src: str, how: str) -> list[dict]:
    """Largest absolute differences and mismatch counts between two (N, 16) output arrays."""
    diff = np.abs(a_out.astype(np.float64) - b_out)
    ent = []
    for name in CHECK_FIELDS:
        j = OUT_FIELDS.index(name)
        ent.append(dict(name=f"export_severity.{label}.{who}.max_abs_diff.{name}", value=float(diff[:, j].max()), unit=_unit(name), origin="MEASURED_SOFTWARE", source_file=src,
                        notes=f"{how} against {against} on {len(a_out)} windows; single against double precision"))
    for key, field in (("class_mismatches", "severity_class"), ("rollover_flag_mismatches", "rollover"), ("roll_correction_applied_mismatches", "roll_corrected_applied"), ("thiv_hit_mismatches", "thiv_hit")):
        j = OUT_FIELDS.index(field)
        ent.append(dict(name=f"export_severity.{label}.{who}.{key}", value=int((a_out[:, j] != b_out[:, j]).sum()), unit="windows", origin="MEASURED_SOFTWARE", source_file=src,
                        notes=f"{how} against {against}: different value of {field}"))
    return ent


def compare(sets: dict[str, tuple[np.ndarray, np.ndarray]], ent: list[dict]) -> None:
    """Compare the C code with Python on every window (if the compiled program can run) and the pure-Python float32 mirror with Python on a subset.

    If Windows blocks the compiled program, the C entries are recorded as NOT_RUN with the reason and the mirror results remain. Nothing is carried over from an earlier run.
    """
    from crashguard.c_mirror import severity_mirror

    src = str(HEADER)
    py = {label: python_severity(a, g) for label, (a, g) in sets.items()}
    for label, (a, g) in sets.items():
        ent.append(dict(name=f"export_severity.{label}.windows", value=int(len(a)), unit="windows", origin="MEASURED_SOFTWARE", source_file=src))
        idx = np.unique(np.linspace(0, len(a) - 1, min(MIRROR_N, len(a))).astype(int))
        m_out = np.array([[severity_mirror(a[i], g[i], C.PRE_N)[k] for k in OUT_FIELDS] for i in idx])
        ent.append(dict(name=f"export_severity.{label}.mirror.windows", value=int(len(idx)), unit="windows", origin="MEASURED_SOFTWARE", source_file=src, notes="evenly spaced subset"))
        ent += _diff_entries(label, "mirror", m_out, py[label][idx], "Python", src, "pure-Python float32 mirror of severity.h")
        print(label, "mirror", {n: float(np.abs(m_out[:, OUT_FIELDS.index(n)] - py[label][idx][:, OUT_FIELDS.index(n)]).max()) for n in ("dv_res_kmh", "asi", "tilt_deg")})
    try:
        c_all, cc = c_severity(np.concatenate([a for a, _g in sets.values()]), np.concatenate([g for _a, g in sets.values()]))
    except RuntimeError as err:
        for label in sets:
            ent.append(dict(name=f"export_severity.{label}.c.max_abs_diff.dv_res_kmh", value="NOT_RUN", unit="km/h", origin="NOT_RUN", source_file=src,
                            notes=f"compiled C check could not run: {str(err)[:160]}; the pure-Python mirror was run instead"))
        return
    pos = 0
    for label, (a, g) in sets.items():
        c_out = c_all[pos:pos + len(a)]
        pos += len(a)
        ent += _diff_entries(label, "c", c_out, py[label], "Python", src, f"C ({cc})")
        jc = OUT_FIELDS.index("severity_class")
        print(label, "C", {n: float(np.abs(c_out[:, OUT_FIELDS.index(n)] - py[label][:, OUT_FIELDS.index(n)]).max()) for n in ("dv_res_kmh", "asi", "thiv_kmh")}, "class mismatches", int((c_out[:, jc] != py[label][:, jc]).sum()), "of", len(a))


