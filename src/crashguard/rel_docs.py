def negatives_block(r: dict) -> str:
    L = ["## Release (V7) negatives", "",
         "| Item | Verdict | Label | Where |", "|---|---|---|---|",
         "| Physics generators PH-A, PH-B and the refit family generator | fail the realism gate in every mode | SIMULATED | `docs/03_results/PH_INTEGRITY_REPORT.md` |",
         f"| VZCrash-style surrogate | fails the discriminator gate (AUC {v(r, 'ph.surrogate.auc')}) | SIMULATED | `ph.surrogate.*` |",
         "| H-A1 OS-DR (overhear-and-suppress, deadline-aware retries) | NOT SUPPORTED | SIMULATED | `pa.holm.ha1.*` |",
         "| H-A2 GS-CA (GPS-slotted, cluster-aware critical alerts) | NOT SUPPORTED | SIMULATED | `pa.holm.ha2.*` |",
         "| H-A3 security regression for OS-DR | NOT SUPPORTED (event-level forged ACK by a key holder) | ANALYTICAL | `pa.model.*` |",
         "| Q reruns H-Q1a to H-Q1c | NOT SUPPORTED, same as the original | MEASURED_SOFTWARE | `q.holm.*` |", ""]
    return "\n".join(L)


def claims_block(r: dict) -> str:
    return "\n".join(["## Release (V7) claims", "",
        "| Claim | Evidence label | Section | Verdict |", "|---|---|---|---|",
        "| Physics-based generators with stated assumptions were built and checked against real data; none of them passes the realism gate (point AUC at most 0.60) in any mode, so none trains a confirmatory rerun. | SIMULATED | Physics generator integrity report | gate failed |",
        "| With no gated synthetic data, the real-only reruns of H-P1, H-P2 and H-P3a give the same verdicts as the original studies. | MEASURED_SOFTWARE | Release results, Q4 table | unchanged |",
        "| Under the stated assumptions, overhear-and-suppress retries (OS-DR) and GPS-slotted critical alerts (GS-CA) do not raise critical reach within 10 s by 5 points in 60% of held-out cells. | SIMULATED | Release results, block A | H-A1 and H-A2 NOT SUPPORTED |",
        "| In a bounded model, one forged event-level acknowledgement from a holder of the shared key stops every vehicle of a cell; the per-vehicle acknowledgement needs one forged frame per vehicle. | ANALYTICAL (model, not implementation) | Release results, block A | H-A3 NOT SUPPORTED |", ""])


def main() -> None:
    r = load()
    Path("docs/03_results/RELEASE_RESULTS.md").write_text(results(r), encoding="utf-8")
    replace_block(Path("docs/03_results/NEGATIVES_REGISTER.md"), "<!-- v7:start -->", "<!-- v7:end -->", negatives_block(r))
    replace_block(Path("docs/00_overview/CLAIMS_FOR_COVER_LETTER.md"), "<!-- v7:start -->", "<!-- v7:end -->", claims_block(r))
    print("wrote docs/03_results/RELEASE_RESULTS.md and the V7 block of the negatives register")


if __name__ == "__main__":
    main()
