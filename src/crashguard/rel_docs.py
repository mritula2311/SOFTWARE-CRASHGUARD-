          f"| H-A1 | cells lost by more than 2 points (need 0) | {v(r, 'pa.hA1.n_cells_lose2', 0)} |",
          f"| H-A1 | node airtime share, OS-DR minus best earlier (upper end must be at most 0) | {ci(r, 'pa.hA1.duty_use_diff', 4)} |",
          f"| H-A1 | non-severe escalation, OS-DR minus best earlier (upper end must be at most 0) | {ci(r, 'pa.hA1.escalation_diff', 3)} |",
          f"| H-A2 | burst cells with a gain over OS-DR / over the slot-probability baseline (need at least 10 of 16) | {v(r, 'pa.hA2.vs_osdr.n_cells_gain5', 0)} / {v(r, 'pa.hA2.vs_tamang.n_cells_gain5', 0)} |",
          f"| H-A2 | burst cells lost by more than 2 points, against OS-DR / against the baseline | {v(r, 'pa.hA2.vs_osdr.n_cells_lose2', 0)} / {v(r, 'pa.hA2.vs_tamang.n_cells_lose2', 0)} |",
          f"| H-A3 | counterexample for OS-DR, attacker without the key / with the shared key (event silently lost) | {'yes' if v(r, 'pa.model.osdr.nokey.violated.S4', 0) == '1' else 'no'} / {'yes' if v(r, 'pa.model.osdr.key.violated.S4', 0) == '1' else 'no'}; shortest attack: {v(r, 'pa.model.osdr.key.attacker_actions_to_lose_event', 0)} action; baseline needs {v(r, 'pa.model.baseline.key.attacker_actions_to_lose_event', 0)} |",
