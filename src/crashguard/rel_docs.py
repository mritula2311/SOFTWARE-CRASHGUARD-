"""Release results document (generated from results/results.json and the result tables; no number is typed): docs/03_results/RELEASE_RESULTS.md, plus V7 blocks appended to the negatives register and the claim list.

    python -m crashguard.rel_docs
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from crashguard.docs_gen import replace_block

R = Path("results/results.json")


def load() -> dict:
    return {e["name"]: e for e in json.loads(R.read_text(encoding="utf-8"))}


def v(r: dict, k: str, d: int = 3):
    e = r.get(k)
    if e is None or e["value"] is None:
        return "NOT_RUN"
    x = e["value"]
    return f"{x:.{d}f}" if isinstance(x, float) else str(x)


def ci(r: dict, k: str, d: int = 3) -> str:
    return f"{v(r, k, d)} [{v(r, k + '_lo', d)}, {v(r, k + '_hi', d)}]"


def verdict_of(r: dict, k: str) -> str:
    e = r.get(k)
    return "not available" if e is None else str(e["value"])


def q4(r: dict) -> list[str]:
    rows = [("H-P1 (hq1a)", "p.holm.hp1.verdict", "hq1a", "q.fam_f1.cv.hF1.criterion_met", "q.pha_ungated.sealed.hF1.criterion_met"),
            ("H-P2 (hq1b)", "p.holm.hp2.verdict", "hq1b", "q.fam_f1.cv.hF1b.criterion_met", "q.pha_ungated.sealed.hF1b.criterion_met"),
            ("H-P3a (hq1c)", "p.holm.hp3a.verdict", "hq1c", "q.fam_f1.cv.hF1c.criterion_met", "q.pha_ungated.sealed.hF1c.criterion_met")]
    L = ["| Hypothesis | Original verdict | Real-only rerun (ratio 0) | Family-generator arm (EXPLORATORY, cross-validation) | PH-A arm (EXPLORATORY, gate failed, sealed fold only: the cross-validation runs did not finish) | PH-B arm | Changed |", "|---|---|---|---|---|---|---|"]

    def word(k):
        e = r.get(k)
        if e is None:
            return "NOT_RUN"
        return "criterion met" if e["value"] in (1, True) else ("NOT_RUN" if e["value"] == "NOT_RUN" else "criterion not met")

    for name, orig, hid, fam, pha in rows:
        real = verdict_of(r, f"q.holm.{hid}.verdict")
        o = verdict_of(r, orig)
        L.append(f"| {name} | {o} | {real} | {word(fam)} | {word(pha)} | NOT_RUN (not started: time) | {'no' if o == real else 'yes'} |")
    for hid, orig_key, label in (("hq1d", "x.holm.H-X5.verdict", "H-X5"), ("hq1e", "x.holm.H-X6.verdict", "H-X6"), ("hq1f", "x.holm.H-X7.verdict", "H-X7"), ("hq2a", "p.holm.hp4a.verdict", "H-P4a"), ("hq2b", "p.holm.hp4b.verdict", "H-P4b"),
                                 ("hq2c", "p.holm.hp4c.verdict", "H-P4c"), ("hq2d", "x.holm.H-X1.verdict", "H-X1"), ("hq2e", None, "H-X2"), ("hq2f", "x.holm.H-X3.verdict", "H-X3"), ("hq2g", "x.holm.H-X8.verdict", "H-X8"), ("hq2h", None, "early exit N19"),
                                 ("hq3a", "f.holm.hf3a.verdict", "N28"), ("hq3b", "f.holm.hb2.verdict", "H-B2"), ("hq3c", "f.holm.hf3b.verdict", "P3b")):
        o = verdict_of(r, orig_key) if orig_key else "NOT_RUN (original)"
        new = verdict_of(r, f"q.holm.{hid}.verdict")
        L.append(f"| {label} ({hid}) | {o} | {new} | not run (no gated synthetic data) | not run | not run | {'no' if (o == new or new == 'NOT RUN') else 'yes'} |")
    return L


