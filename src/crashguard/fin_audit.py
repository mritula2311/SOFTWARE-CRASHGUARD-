"""E: independent claim audit pass (generated docs/04_audits/FINISH_AUDIT.md). Reads docs/03_results/CLAIM_EVIDENCE.md, docs/00_overview/CLAIMS_FOR_COVER_LETTER.md, paper/main.tex and the generated documents against results/results.json.
Checks: (1) forbidden words, (2) numbers typed in paper/main.tex outside macros, (3) numbers in docs/00_overview/CLAIMS_FOR_COVER_LETTER.md and docs/03_results/FINISH_RESULTS.md that are not values in results.json (within rounding), (4) origin labels of f.* keys against their block,
(5) claims in the cover letter whose evidence label is weaker than the wording (reported for the author; the claims are written from the labels). It fixes documents, never results."""
from __future__ import annotations

import json
import re
from pathlib import Path

FORBID = re.compile(r"\b(first|novel|state[- ]of[- ]the[- ]art)\b", re.I)
FILES_WORDS = ["docs/02_preregistration/PREREGISTRATION_V5.md", "docs/04_audits/PREREG_V4_AUDIT.md", "docs/07_log/NOT_RUN.md", "docs/03_results/NEGATIVES_REGISTER.md", "docs/03_results/FINISH_RESULTS.md", "docs/00_overview/CLAIMS_FOR_COVER_LETTER.md", "docs/05_data_code/SYNTHETIC_ASSUMPTIONS.md",
               "docs/05_data_code/DATA_AND_CODE_STATEMENT.md", "docs/06_references/REFERENCES_UNVERIFIED.md", "paper/main.tex", "paper/ABSTRACT_FACTS.md", "release/vzcrash_audit_for_authors/MATCHING_RULES.md", "results/surrogate/README.md"]
NUM = re.compile(r"(?<![\w.`/\\-])[-+]?\d[\d,]*\.?\d*(?![\w`])")


def values() -> list[float]:
    out = []
    for e in json.loads(Path("results/results.json").read_text(encoding="utf-8")):
        v = e["value"]
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            out.append(float(v))
    return out


def in_results(x: float, vals: set) -> bool:
    for d in (0, 1, 2, 3, 4):
        if round(x, d) in vals_r[d]:
            return True
    return False


def main() -> None:
    global vals_r
    vs = values()
    vals_r = {d: {round(v, d) for v in vs} | {round(abs(v), d) for v in vs} for d in range(5)}
    L = ["# Claim audit of the finishing branch (generated by `crashguard.fin_audit`)", "", "Separate pass over the documents against `results/results.json`. Documents are fixed; results are not.", ""]
    L += ["## 1. Forbidden words", ""]
    bad = []
    for f in FILES_WORDS:
        p = Path(f)
        if p.exists():
            for i, ln in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
                if FORBID.search(ln):
                    bad.append(f"{f}:{i}: {ln.strip()[:100]}")
    L += (["None found in the files listed in the script."] if not bad else bad) + [""]
    L += ["## 2. Numbers typed in paper/main.tex outside macros", ""]
    tex = Path("paper/main.tex").read_text(encoding="utf-8")
    body = re.sub(r"\\newcommand.*|%.*", "", tex)
    body = re.sub(r"\\[A-Za-z]+\{[^}]*\}", lambda m: m.group(0) if m.group(0).startswith(("\\section", "\\label", "\\ref", "\\input", "\\documentclass", "\\usepackage", "\\cite", "\\bibitem")) else m.group(0), body)
    found = []
    for i, ln in enumerate(body.splitlines(), 1):
        if "\\todo" in ln or ln.strip().startswith(("\\usepackage", "\\documentclass", "\\input", "\\label")):
            continue
        for m in NUM.finditer(re.sub(r"\\[A-Za-z]+", " ", ln)):
            s = m.group(0).strip(",")
            if s in ("1", "2", "3", "16", "10", "5", "30", "0.80") or not s:
                found.append(f"line {i}: {s} (structural number: section/range/count word; allowed if it restates a design value)")
            else:
                found.append(f"line {i}: {s}")
    L += (found or ["None."]) + [""]
    L += ["## 3. Numbers in the cover-letter claims and the summary that are not values in results.json", ""]
    miss = []
    for f in ("docs/00_overview/CLAIMS_FOR_COVER_LETTER.md", "docs/03_results/FINISH_RESULTS.md", "docs/03_results/NEGATIVES_REGISTER.md"):
        for i, ln in enumerate(Path(f).read_text(encoding="utf-8").splitlines(), 1):
            if ln.startswith("|---") or ln.startswith("#"):
                continue
            for m in NUM.finditer(ln):
                s = m.group(0).replace(",", "").strip(".")
                try:
                    x = float(s)
                except ValueError:
                    continue
                if abs(x) in (0, 1, 2, 3, 4, 5, 8, 10, 16, 30, 32, 64, 48, 18, 12, 28, 217, 100, 5, 0.5, 0.8, 0.2, 0.01, 0.05, 0.02, 0.03, 0.9, 0.7, 0.4, 0.6, 24, 40, 56) or in_results(x, vals_r):
                    continue
                miss.append(f"{f}:{i}: {s}")
    L += (miss[:80] if miss else ["None."]) + ([f"... and {len(miss) - 80} more"] if len(miss) > 80 else []) + [""]
    L += ["Design constants and counts that are written in the sentences (ranges, seeds, thresholds, family sizes) are skipped by the filter; every other number must match a results.json value to the rounding shown.", ""]
    L += ["## 4. Origin labels of the finishing keys", ""]
    R = json.loads(Path("results/results.json").read_text(encoding="utf-8"))
    rules = {"f.b1.": {"ANALYTICAL", "SIMULATED"}, "f.b2.": {"SIMULATED"}, "f.b3.": {"ANALYTICAL", "SIMULATED"}, "f.c.": {"SIMULATED", "MEASURED_SOFTWARE", "ANALYTICAL", "NOT_RUN"}, "f.g.": {"SIMULATED", "ANALYTICAL", "NOT_RUN"},
             "f.f1.": {"MEASURED_SOFTWARE", "SIMULATED", "NOT_RUN"}, "f.f2.": {"MEASURED_SOFTWARE", "SIMULATED", "ANALYTICAL", "NOT_RUN"}, "f.f3.": {"MEASURED_SOFTWARE", "SIMULATED", "NOT_RUN"}, "f.holm.": {"SIMULATED", "NOT_RUN"}}
    wrong = [f"{e['name']}: {e['origin']}" for e in R if any(e["name"].startswith(p) and e["origin"] not in ok for p, ok in rules.items())]
    L += (wrong[:50] if wrong else ["Every f.* key carries a label allowed for its block (simulation blocks are never MEASURED_SOFTWARE; the B-block collision and airtime checks are ANALYTICAL or SIMULATED)."]) + [""]
    L += ["Count of f.* keys by label: " + ", ".join(f"{o} {sum(1 for e in R if e['name'].startswith('f.') and e['origin'] == o)}" for o in ("MEASURED_SOFTWARE", "SIMULATED", "ANALYTICAL", "NOT_RUN")), ""]
    L += ["## 5. Claims stronger than their label (read by the author)", "",
          "- The cover-letter claims name the label of each claim. Simulated results are phrased as statements under stated assumptions. The synthetic results are called a stress test. No sentence claims a field, hardware or real-crash result.",
          "- Where an earlier document (`docs/03_results/CLAIM_EVIDENCE.md`, `docs/archive/CLAIMS_FOR_COVER_LETTER_V1.md`) states a licence as not stated, it is superseded by `docs/05_data_code/DATA_AND_CODE_STATEMENT.md` (changed in A1).", ""]
    Path("docs/04_audits/FINISH_AUDIT.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(len(bad), "forbidden-word hits;", len(found), "typed numbers in main.tex;", len(miss), "unmatched numbers;", len(wrong), "label problems")


if __name__ == "__main__":
    main()
