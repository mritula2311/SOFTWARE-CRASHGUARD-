    for g in GENS:
        for m in MODES:
            p = f"ph.control.{g}.{m}"
            if f"{p}.tstr_macro_f1" not in r:
                continue
            L.append(f"| {g} | {m} | {v(r, p + '.tstr_macro_f1')} | {v(r, p + '.real_real_macro_f1')} | {v(r, p + '.shuffled_label_macro_f1')} | {v(r, p + '.trts_macro_f1_diagnostic')} |")
