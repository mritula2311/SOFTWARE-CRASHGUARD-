"""Writes the table-to-command section of docs/05_data_code/REPRODUCE.md from docs/05_data_code/FIGURES_TABLES.md.

Each table or figure names the ``results.json`` key prefix behind it; the prefix is mapped to the module that writes it. Running that module again (after the full run has built its inputs) recomputes the numbers; ``python -m crashguard.report``
renders them. Prefixes that no module is mapped to are listed in the section so that nothing is silently dropped.
"""
from __future__ import annotations

from crashguard.textutil import clip

import re
from pathlib import Path

from crashguard.docs_gen import replace_block

DOC = Path("docs/05_data_code/REPRODUCE.md")
INDEX = Path("docs/05_data_code/FIGURES_TABLES.md")
START, END = "<!-- repro_tables:start -->", "<!-- repro_tables:end -->"

MODULE = {
    "vzcrash": "data", "leakage": "split", "s2": "models", "s3": "models", "s4": "models", "s4b": "detector_extra", "gap": "models", "confusion3": "models", "lovso": "models", "ap_by_size": "models", "peak_window": "models",
    "detector": "detector_extra", "candidate": "detector_extra", "prev": "prevalence", "trigger": "features", "robust": "robustness", "export": "export_c", "export_severity": "export_severity",
    "severity_synth": "severity_synth", "nhtsa": "nhtsa", "sevstudy": "severity_study", "severity_vzcrash": "severity_vzcrash", "attacks": "attacks", "forgery": "forgery", "counter": "forgery", "replay": "replay_study",
    "n14": "saturation_study", "n14x": "saturation_splits", "n14s": "s4_n14", "n15": "trigger_aware", "n16": "scheduler_study", "lora": "lora", "s9": "delivery_sim", "x1": "direction", "x2": "injury", "x3": "early", "x4": "conformal",
    "x5": "spoofing", "x6": "capacity", "x7": "physical_scaling", "n20c": "s3_conformal", "dupscan": "s2_dedup", "n24": "s9_conformal_dv", "s10": "s10_adaptive", "ua": "ua_conformal", "s11": "s11_sct", "s13": "s13_spaced_table",
    "s12": "protocol_check", "s12x": "protocol_check_ext", "s5": "s5_burst", "s6": "s6_early", "hw": "ingest_hardware", "t1": "t1_equal_escalation", "t2": "t2_pareto", "t3": "t3_cost", "t4": "t4_clarify", "t5": "t5_strict",
    "t6": "t6_thresholds", "t7": "t7_conformal_variants", "t8": "t8_sweep", "t9": "t9_ablations", "t10": "t10_airtime", "t13": "t13_second_dataset", "t14": "stats_audit", "attacks_x": "attacks_extra",
}
V2_TABLES = [("v2_tab_estimators", "A: clipping estimators", "python -m crashguard.v2_a_study"), ("v2_tab_bounds", "A2: bounds", "python -m crashguard.v2_a_study"), ("v2_tab_intervals", "A5: conformal intervals by clipped-fraction bin", "python -m crashguard.v2_a_study"),
             ("v2_tab_abstention", "A6: abstention flag", "python -m crashguard.v2_a_study"), ("v2_tab_onset_flag", "D: clip-onset flag", "python -m crashguard.v2_d_study"), ("v2_tab_adaptive", "B: adaptive variants against matched baselines", "python -m crashguard.v2_b_study"),
             ("v2_tab_sensitivity", "B5: sensitivity", "python -m crashguard.v2_b_sens"), ("v2_tab_tag_length", "E: tag length", "python -m crashguard.v2_e_study"), ("v2_tab_hold_cost_grid", "F1: hold cost grid", "python -m crashguard.v2_f_study"),
             ("v2_tab_hold_sim", "F2: hold simulation", "python -m crashguard.v2_f_study"), ("v2_tab_verdicts", "all: verdicts and Holm correction", "python -m crashguard.v2_verdicts")]
SPECIAL = {"hw": "python merge/ingest_hardware.py (NOT_RUN: the author's hardware logs are not read in this software-only run)", "results/tables/replay_grid": "python -m crashguard.replay_study"}


def command(keys: str) -> tuple[str, str]:
    """(command, status) for the first key prefix of an index row."""
    first = re.split(r"[,;]\s*", keys.strip())[0].strip().strip("`")
    if first.startswith("results/tables/"):
        return SPECIAL.get("results/tables/replay_grid", ""), "ok"
    pre = first.split(".")[0]
    if pre in SPECIAL:
        return SPECIAL[pre], "ok"
    if pre in MODULE:
        return f"python -m crashguard.{MODULE[pre]}", "ok"
    return "", pre


def render() -> str:
    rows, unmapped = [], set()
    for line in INDEX.read_text(encoding="utf-8").splitlines():
        if not (line.startswith("| Table") or line.startswith("| Figure")):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        item, title, keys = cells[0], cells[1], cells[3]
        cmd, st = command(keys)
        if st != "ok":
            unmapped.add(st)
        rows.append(f"| {item} | {clip(title, 90)} | `{clip(keys, 60)}` | {'`' + cmd + '`' if cmd else 'not mapped'} |")
    out = ["## 8. One command per table and figure (generated by `python -m crashguard.repro_table`)", "",
           "Run `.\\scripts\\run_all.ps1` once (it builds every input in order). After that, the command in the last column recomputes that table's numbers and `python -m crashguard.report` renders them again. "
           "Tables and figures from the closing block (T1 to T14) also have CSV and LaTeX versions in `results/paper/`, written by `python -m crashguard.paper_tables`; every row there names its `results.json` key.", "",
           "| Item | Title | results.json keys | Command |", "|---|---|---|---|"] + rows
    out += ["", f"Key prefixes without a mapped module: {', '.join(sorted(unmapped)) if unmapped else 'none'}."]
    out += ["", "## 9. One command per v2 table (branch `v2-algorithms`; plan: `docs/02_preregistration/PREREGISTRATION_V2.md`, results: `docs/03_results/V2_RESULTS.md`)", "",
            "Run `scripts/run_all.ps1` once (the v2 steps follow the T block), or run the commands below in this order after the earlier steps: A, D, B, B5, E, F, verdicts, documents, tables. "
            "Each table has a CSV and a LaTeX version in `results/paper/`; every row names its `results.json` key.", "", "| Table | Study | Command that computes it | Command that writes the table |", "|---|---|---|---|"]
    for tab, study, cmd in V2_TABLES:
        out.append(f"| `results/paper/{tab}.csv`, `.tex` | {study} | `{cmd}` | `python -m crashguard.v2_paper_tables` |")
    out += ["", "Study C was not run (see `docs/03_results/V2_RESULTS.md`). The verdicts and the Holm correction: `python -m crashguard.v2_verdicts`; the results document: `python -m crashguard.v2_docs`; the claim rows: `python -m crashguard.claim_table`."]
    return "\n".join(out)


def main() -> None:
    replace_block(DOC, START, END, render())
    print(f"wrote the table-to-command section into {DOC}")


if __name__ == "__main__":
    main()
