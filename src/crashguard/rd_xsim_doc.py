"""Writes docs/03_results/XSIM_CALIBRATION.md and the ``rd.x1.*`` keys from the stored calibration runs (``data/processed/rd_xsim_custom.json``, ``rd_xsim_ns3_matched.json``, ``rd_xsim_supp.json``).

    python -m crashguard.rd_xsim_doc
"""
from __future__ import annotations

import json
import math
from pathlib import Path

from crashguard.rd_common import Rec

HDR = """# Cross-simulator calibration (X1.2): custom simulator against ns-3 lorawan

<!-- header:start -->
| Field | Value |
|---|---|
| Status | current |
| Date | 2026-11-14 |
| Owner | Mritula S |
| Scope | Packet delivery ratio of baseline scenarios in the custom simulator and in ns-3 lorawan, the pre-stated agreement criterion and its verdict (generated). |
| Evidence labels used | SIMULATED, NOT_RUN |
| Abbreviations | ACK = acknowledgement frame; ADR = adaptive data rate; PDR = packet delivery ratio; SF = spreading factor |
<!-- header:end -->

Generated by `python -m crashguard.rd_xsim_doc`. Build record: `docs/03_results/XSIM_BUILD.md`. Scenario code: `xsim/ns3/xsim_calib.cc` (ns-3) and `src/crashguard/rd_xsim.py` (both sides). Constants: `docs/03_results/ASSUMPTIONS.md`.

**Scenario.** One gateway at the centre of a disc of radius 3,000 m; N vehicles placed uniformly (a new placement and shadowing draw in every run); one spreading factor; 97-byte frames every 30 s on average (periodic with a random phase in ns-3, Poisson arrivals in the custom simulator, a stated difference); one transmission and no retry; unconfirmed or confirmed uplink; no extra random loss. Channel on both sides: path-loss exponent 3 with 25 dB at 1 m, 10 dB vehicle loss, static log-normal shadowing of 6 dB per vehicle, 2 dB fading per packet, 6 dB same-spreading-factor capture, gateway and device sensitivities of the custom simulator (-123, -126, -129 dBm for SF7, SF8, SF9). ns-3 uses its own receiver and interference model, so the comparison tests the two simulators' collision and reception logic, not only the shared constants. N = 1, 10, 50, 100; SF7 and SF9. Samples: 60 hours (custom) and 60 runs (ns-3) per cell.

**Pre-stated agreement criterion** (`PREREGISTRATION_V12.md` section 8): the absolute PDR difference is at most 5 points in every baseline cell.
"""


def main() -> None:
    c = json.loads(Path("data/processed/rd_xsim_custom.json").read_text(encoding="utf-8"))
    n = json.loads(Path("data/processed/rd_xsim_ns3_matched.json").read_text(encoding="utf-8"))
    rec = Rec("rd.x1.", "src/crashguard/rd_xsim_doc.py")
    L = [HDR, "## Results\n", "| N | SF | Uplink | Custom PDR | ns-3 PDR | Difference (custom minus ns-3) | Within 5 points |\n|---|---|---|---|---|---|---|"]
    mx, bad = 0.0, []
    for a, b in zip(c, n):
        d = a["pdr"] - b["pdr"]
        mx = max(mx, abs(d))
        ok = abs(d) <= 0.05
        if not ok:
            bad.append(f"N={a['n']} SF{a['sf']} {a['mode']}")
        L.append(f"| {a['n']} | {a['sf']} | {a['mode']} | {a['pdr']:.3f} | {b['pdr']:.3f} | {d:+.3f} | {'yes' if ok else 'NO'} |")
        key = f"cell.n{a['n']}_sf{a['sf']}_{a['mode']}"
        rec.add(f"{key}.pdr_custom", a["pdr"], "fraction", "custom simulator, 60 simulated hours")
        rec.add(f"{key}.pdr_ns3", b["pdr"], "fraction", f"ns-3 lorawan, {b['runs_ok']} runs of 3,600 s")
        rec.add(f"{key}.diff", d, "fraction", "custom minus ns-3")
        if a.get("ack_share") is not None:
            rec.add(f"{key}.ack_share_custom", a["ack_share"], "fraction", "share of confirmed uplinks whose ACK reached the vehicle (custom)")
    met = not bad
    rec.add("max_abs_diff", mx, "fraction", "largest absolute PDR difference over the 16 baseline cells")
    rec.add("cells_above_5pt", len(bad), "cells", "cells with an absolute difference above 0.05")
    rec.add("criterion_met", int(met), "flag", "the pre-stated criterion: every cell within 5 points")
    L.append(f"\n**Verdict on the pre-stated criterion: {'MET' if met else 'NOT MET'}.** Largest absolute difference {mx:.3f}; cells above 5 points: {len(bad)} ({', '.join(bad) or 'none'}).")
    for a, b in zip(c, n):
        if abs(a["pdr"] - b["pdr"]) > 0.05:
            L.append(f"\nThe cell N={a['n']}, SF{a['sf']}, {a['mode']} differs by {a['pdr'] - b['pdr']:+.3f}. With one vehicle the PDR is set by where that vehicle is placed, so 60 placements give a standard error of about {math.sqrt(2) * math.sqrt(a['pdr'] * (1 - a['pdr']) / 60):.3f} on the difference (a binomial approximation); the difference is inside that noise. The preregistered criterion is not relaxed on this account.")
    sp = Path("data/processed/rd_xsim_supp.json")
    if sp.exists():
        s = json.loads(sp.read_text(encoding="utf-8"))
        L.append("\n### Supplementary: the four single-vehicle cells with 300 placements per side (not part of the criterion; reported next to the main table)\n")
        L.append("| SF | Uplink | Custom PDR | ns-3 PDR | Difference |\n|---|---|---|---|---|")
        for a, b in zip(s["custom"], s["ns3"]):
            L.append(f"| {a['sf']} | {a['mode']} | {a['pdr']:.3f} | {b['pdr']:.3f} | {a['pdr'] - b['pdr']:+.3f} |")
            rec.add(f"supp.n1_sf{a['sf']}_{a['mode']}.diff", a["pdr"] - b["pdr"], "fraction", "supplementary, 300 placements per side")
    cb, nb = Path("data/processed/rd_xsim_custom_b.json"), Path("data/processed/rd_xsim_ns3_b.json")
    if cb.exists() and nb.exists():
        cbj, nbj = json.loads(cb.read_text(encoding="utf-8")), json.loads(nb.read_text(encoding="utf-8"))
        L.append("\n## Setting (b): both simulators at ns-3's shipped gateway sensitivity (V12 11.3)\n")
        L.append("Gateway sensitivity -130, -132.5, -135, -137.5, -140, -142.5 dBm for SF7 to SF12 in both simulators (in ns-3 the end-device table is set to the same values, a stated deviation from the shipped end-device table); same scenarios and sample sizes as setting (a); the local ADR backoff is off. **Setting (a) above is the setting of every X1.3 verdict.**\n")
        L.append("| N | SF | Uplink | Custom PDR | ns-3 PDR | Difference (custom minus ns-3) | Within 5 points |\n|---|---|---|---|---|---|---|")
        mxb, badb = 0.0, []
        for a, b in zip(cbj, nbj):
            d = a["pdr"] - b["pdr"]
            mxb = max(mxb, abs(d))
            if abs(d) > 0.05:
                badb.append(f"N={a['n']} SF{a['sf']} {a['mode']}")
            L.append(f"| {a['n']} | {a['sf']} | {a['mode']} | {a['pdr']:.3f} | {b['pdr']:.3f} | {d:+.3f} | {'yes' if abs(d) <= 0.05 else 'NO'} |")
            key = f"cell.n{a['n']}_sf{a['sf']}_{a['mode']}"
            rec.add(f"b.{key}.diff", d, "fraction", "setting (b), custom minus ns-3")
        rec.add("b.max_abs_diff", mxb, "fraction", "setting (b): largest absolute PDR difference over the 16 baseline cells")
        rec.add("b.cells_above_5pt", len(badb), "cells", "setting (b): cells above 0.05")
        rec.add("b.criterion_met", int(not badb), "flag", "setting (b): every cell within 5 points")
        L.append(f"\n**Verdict on the pre-stated criterion under setting (b): {'MET' if not badb else 'NOT MET'}.** Largest absolute difference {mxb:.3f}; cells above 5 points: {len(badb)} ({', '.join(badb) or 'none'}).")
        L.append(f"\n**Both settings (A3).** Setting (a): criterion {'MET' if met else 'NOT MET'} (largest difference {mx:.3f}). Setting (b): {'MET' if not badb else 'NOT MET'} (largest difference {mxb:.3f}). The original criterion (setting (a)) was missed by one cell at 5.4 points and is reported as a limitation of the cross-simulator comparison whatever setting (b) shows; no constant of the custom simulator was changed to make either setting pass.")
    L.append("""
## What the calibration found (and what it did not)
- **ns-3's shipped gateway sensitivity is 7 dB better than the value assumed in the custom simulator** (SF7: -130 against -123 dBm; SF9: -135 against -129 dBm; the end-device table is 1 dB different). With the shipped values a quick 5-run check of the same cells gave differences of up to 0.22 (single vehicle, SF7); those runs were not kept after the patch, so a rerun with the unpatched build is NOT_RUN. The comparison above uses a local patch of the two sensitivity tables in the ns-3 source (recorded in `XSIM_BUILD.md`). Which sensitivity is right for the real radio is not settled here; the custom simulator's value is an assumption of this repository.
- ns-3's local adaptive-data-rate backoff changes the data rate after about 96 uplinks without a downlink; it was switched off in the scenario (`SetUplinkAdrBit(false)`). Before that fix the delivery of a single vehicle fell with the run length (0.92 at 300 s to 0.60 at 3,600 s), which is how it was found.
- The ns-3 default transmit power (14 dBm) is kept and the 10 dB vehicle loss is applied in the channel instead.
- Not run: confirmed-uplink ACK success in ns-3 (the tracker counts MAC receptions only); SF11 and SF12 (the ns-3 ALOHA region has no valid data rate for them); more than one gateway.

## X1.3 and X1.4
- **X1.3, D1 as an ns-3 application and the cross-simulator verdict table: run in session 2 for D1 (not D2, already a negative result): `docs/03_results/XSIM_VERDICTS.md`.** The verdicts of H-D1a and H-D1b differ between the simulators; D1 is simulator-dependent. The calibration criterion above was not met, and the verdicts are stated under that condition.
- **X1.4, comparison with published numbers (the ns-3 LoRa simulation paper, ICC 2018; the single-gateway model, IEEE TWC 2021; the real-versus-simulated deployment study, IEEE Sensors J. 2022): NOT_RUN.** None of the three was opened in session 1.
""")
    rec.add("x13.status", "NOT_RUN", "status", "D1 and D2 as ns-3 applications and the cross-simulator verdict table are not run in session 1", "NOT_RUN")
    rec.add("x14.status", "NOT_RUN", "status", "the three published ns-3 and deployment papers were not opened in session 1", "NOT_RUN")
    rec.write()
    Path("docs/03_results/XSIM_CALIBRATION.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("written", "criterion met" if met else "criterion NOT met")


if __name__ == "__main__":
    main()
