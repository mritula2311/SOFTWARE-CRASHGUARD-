# ---------------------------------------------------------------- generated blocks inside hand-written files
def _c(r: dict, k: str, d: int = 3) -> str:
    e = r.get(k)
    if e is None or e["value"] in ("NOT_RUN", None):
        return "NOT_RUN"
    x = e["value"]
    return f"{x:.{d}f}" if isinstance(x, float) else str(x)


def _ci(r: dict, k: str, d: int = 3) -> str:
    return f"{_c(r, k, d)} [{_c(r, k + '_lo', d)} to {_c(r, k + '_hi', d)}]"


def _e(r: dict, k: str) -> str:
    e = r.get(k)
    return f"{float(e['value']):.3e}" if e is not None and isinstance(e["value"], (int, float)) else "NOT_RUN"


def replace_block(path: Path, start: str, end: str, text: str) -> None:
    s = path.read_text(encoding="utf-8")
    blk = f"{start}\n{text}\n{end}"
    if start in s and end in s:
        i, j = s.index(start), s.index(end) + len(end)
        s = s[:i] + blk + s[j:]
    else:
        s = s.rstrip("\n") + "\n\n" + blk + "\n"
    path.write_text(s, encoding="utf-8")


