def write_blocks(r: dict) -> None:
    replace_block(Path("README.md"), "<!-- summary:start -->", "<!-- summary:end -->", readme_summary(r))
    replace_block(Path("docs/01_protocol/PACKET_FORMAT.md"), "<!-- security:start -->", "<!-- security:end -->", packet_block(r))
    replace_block(Path("docs/05_data_code/SEVERITY.md"), "<!-- phase2:start -->", "<!-- phase2:end -->", severity_block(r))


def main() -> None:
    r = res()
    FS.write_text(firmware_sync(r), encoding="utf-8")
    HR.write_text(hardware_readiness(r), encoding="utf-8")
    write_blocks(r)
    print(f"wrote {FS}, {HR} and the generated blocks of README.md, docs/01_protocol/PACKET_FORMAT.md and docs/05_data_code/SEVERITY.md")


if __name__ == "__main__":
    main()
