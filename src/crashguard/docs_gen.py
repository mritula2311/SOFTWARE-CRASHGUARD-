def v(r: dict, k: str, fmt: str = "{}"):
    e = r.get(k)
    if e is None or e["value"] in ("NOT_RUN", None):
        return "NOT_RUN" + (f" ({clip(e['notes'], 90)})" if e and e.get("notes") else "")
    return fmt.format(e["value"])


