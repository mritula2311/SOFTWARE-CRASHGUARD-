    spec = importlib.util.spec_from_file_location("ingest_hardware", here / "merge" / "ingest_hardware.py")
    ih = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ih)
    import make_dummy

    out = here / "tests" / "dummy" / "out"
    before = R.read_bytes() if R.exists() else b""
    with tempfile.TemporaryDirectory() as tmp:
        make_dummy.make(Path(tmp))
        sink = ih.analyse(Path(tmp), out, dummy=True)
