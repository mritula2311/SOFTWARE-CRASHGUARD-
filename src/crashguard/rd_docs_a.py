"""Writes docs/03_results/REDESIGN_A_RESULTS.md from the FRESH-A results (keys ``rd.fa.*``, the stored per-event results, the DEV log). Extra aggregates (by loss level, against UA-SCT and quick retries, D2 airtime)
are computed here from the stored FRESH-A results; they are descriptive and are not hypotheses. Keys ``rd.fa.x.*``.

    python -m crashguard.rd_docs_a
"""
from __future__ import annotations

import csv
import json
import pickle
from collections import Counter
from pathlib import Path

import numpy as np

from crashguard import rd_eval as E
from crashguard.rd_common import Rec

HDR = """# Redesign results, FRESH-A: D1 and D2

<!-- header:start -->
| Field | Value |
|---|---|
| Status | current |
| Date | 2026-11-14 |
| Owner | Mritula S |
| Scope | FRESH-A results for D1 and D2 next to the original failures, with the DEV record and the caveats (generated). |
| Evidence labels used | SIMULATED, ANALYTICAL |
| Abbreviations | ACK = acknowledgement frame; DEV = development grid; DP = dynamic programme; SF = spreading factor; UA-SCT = uncertainty-aware SCT |
<!-- header:end -->

Generated by `python -m crashguard.rd_docs_a`. Preregistration: `docs/02_preregistration/PREREGISTRATION_V12.md` (with addendum A). Constants and their sources: `docs/03_results/ASSUMPTIONS.md`. All numbers are SIMULATED (custom simulator, `world_sim.py`) except H-D2c (ANALYTICAL, a bounded model).
The Holm-adjusted p-values are **provisional**: the family has 10 hypotheses, and the three FRESH-B hypotheses (D3, D4a, D4b) are counted at p = 1 until they are run in session 2. Results were produced once from the frozen code (`results/tables/rd_frozen_A.json`) on the grid of `results/tables/rd_fresh_A_grid.json`, drawn after the freeze; the run is marked in `results/tables/rd_fresh_A_done.json`.
"""


def main() -> None:
    r = {e["name"]: e for e in json.loads(Path("results/results.json").read_text(encoding="utf-8")) if e["name"].startswith(("rd.fa.", "rd.d0.", "rd.d2.model."))}
    v = lambda k: r[k]["value"]  # noqa: E731
    grid = json.loads(Path("results/tables/rd_fresh_A_grid.json").read_text(encoding="utf-8"))
    res = pickle.load(open("data/processed/rd_fresh_A_results.pkl", "rb"))
    cells = E.cells_of(grid)
    names = [c["name"] for c in cells]
    pl = {c["name"]: c["p"] for c in cells}
    burst = [c["name"] for c in cells if c["b"] >= 10]
    rec = Rec("rd.fa.x.", "src/crashguard/rd_docs_a.py")
    L = [HDR]
    # --- table of hypotheses
    L.append("## 1. Hypotheses on FRESH-A, next to the original failures\n")
    L.append("| Id | Original failure (old grids) | Redesign | FRESH-A result | Raw p | Holm p (provisional) | Verdict |\n|---|---|---|---|---|---|---|")
    d1a = f"smallest per-cell gain over the severity table {v('rd.fa.d1a.min_cell_diff'):+.3f}, smallest lower bound {v('rd.fa.d1a.min_cell_lb95'):+.3f}; {v('rd.fa.d1a.cells_failing')} of {v('rd.fa.grid.cells')} cells fail"
    d1b = f"gain over the severity table {v('rd.fa.d1b.pt'):+.3f} [{v('rd.fa.d1b.lo'):+.3f}, {v('rd.fa.d1b.hi'):+.3f}] over the {v('rd.fa.d1b.cells')} cells with loss of 40% or more"
    d1c = f"{v('rd.fa.d1c.violations')} of {v('rd.fa.d1c.runs')} runs exceeded the duty limit"
    d1s = f"against the best of six baselines per cell: smallest per-cell difference {v('rd.fa.d1s.min_cell_diff'):+.3f}, mean {v('rd.fa.d1s.mean_diff'):+.3f}; {v('rd.fa.d1s.cells_failing')} cells below -0.02 by lower bound"
    d2a = f"smallest per-cell change in final delivery {v('rd.fa.d2a.min_cell_diff'):+.3f}; {v('rd.fa.d2a.cells_failing')} cells fail"
    d2b = f"Critical within 10 s in burst cells {v('rd.fa.d2b.pt'):+.4f} [{v('rd.fa.d2b.lo'):+.4f}, {v('rd.fa.d2b.hi'):+.4f}] against the 0.05 required"
    d2c = f"no vehicle-key holder stops another vehicle (2 vehicles at the preregistered bounds, 3 at reduced bounds); control reproduces the shared-key counterexample (stopped without delivery: {v('rd.d2.model.osdr_shared_v2.worst_suppressed')} of 2); stolen gateway key stops {v('rd.d2.model.d2_stolen_gateway_key_v2.worst_suppressed')} (outside the claim)"
    rows = [
        ("H-D1a", "UA-SCT lost to the severity table in some steady-state cells and in the single-car 60% loss case (`DIAGNOSIS_UASCT.md`)", "D1: loss-adaptive deadline table", d1a, "D1a"),
        ("H-D1b", "same", "D1", d1b, "D1b"),
        ("H-D1c", "airtime within the duty limit", "D1", d1c, "D1c"),
        ("H-D1s", "(strict baseline check)", "D1", d1s, "D1s"),
        ("H-D2a", "OS-DR lost in 8 of 32 held-out cells; 0.88 of its suppressions hit alerts the base never received (`DIAGNOSIS_OSDR.md`)", "D2: gateway-signed cluster ACK, stop only if listed, defer otherwise", d2a, "D2a"),
        ("H-D2b", "same", "D2", d2b, "D2b"),
        ("H-D2c", "an event-level ACK under a shared key can be forged by any key holder (H-A3)", "D2", d2c, "D2c"),
    ]
    for hid, orig, red, res_txt, k in rows:
        L.append(f"| {hid} | {orig} | {red} | {res_txt} | {v(f'rd.fa.{k}.p_raw'):.4g} | {v(f'rd.fa.{k}.p_holm_provisional'):.4g} | **{v(f'rd.fa.{k}.verdict_provisional')}** |")
    L.append("\nKill criteria of V12: D1 is killed if H-D1a or H-D1b fails (neither failed). D2 is killed if any of H-D2a, H-D2b, H-D2c fails: **H-D2b failed, so D2 is a negative result** and goes to the negatives register next to OS-DR. "
             "The design had a gain in the right direction (the interval is above zero) but far below the 5 points it needed; on the DEV grid the chosen iteration showed about 4.5 points, so the DEV figure overstated the effect on the fresh grid.\n")
    # --- policy means
    L.append("## 2. Mean delivery by policy (descriptive)\n")
    L.append("Mean over the 64 cells; Critical and Severe alerts delivered before their own deadline (Critical 10 s, Severe 30 s), and Critical alerts within 10 s in the 32 burst cells.\n")
    L.append("| Policy | Delivered before deadline (all cells) | Critical within 10 s (burst cells) |\n|---|---|---|")
    for p in E.POLICIES:
        L.append(f"| {p} | {v(f'rd.fa.policy.{p}.mean_deadline_delivery'):.3f} | {v(f'rd.fa.policy.{p}.burst_mean_crit10'):.3f} |")
    L.append("\nP1 = severity table, P4 = UA-SCT, P0 = fixed 3 retries, quick = SCT with 0.3 s spacing, tamang = Tamang-style slots (oracle burst size), khan = Khan-style retries, D1 = loss-adaptive table, D1D2 = D1 plus the cluster ACK.\n")
    # --- by loss level and vs P4/quick
    L.append("## 3. D1 by loss level and against UA-SCT and quick retries (descriptive; events resampled and hours resampled, the wider interval is shown)\n")
    L.append("| Loss level | cells | D1 minus severity table | D1 minus UA-SCT | D1 minus quick retries | D1 minus best baseline of the cell |\n|---|---|---|---|---|---|")
    for lvl in sorted(set(pl.values())):
        cs = [c for c in names if pl[c] == lvl]
        def pool(a, b):
            return E.pooled_boot([(res[c], a, b, "deadline") for c in cs], 0.0)
        a1, a2, a3 = pool("P1", "D1"), pool("P4", "D1"), pool("quick", "D1")
        best = E.pooled_boot([({"b": res[c][E.best_baseline(res[c], "deadline")], "D1": res[c]["D1"]}, "b", "D1", "deadline") for c in cs], 0.0)
        L.append(f"| {lvl:.2f} | {len(cs)} | {a1['pt']:+.3f} [{a1['lo']:+.3f}, {a1['hi']:+.3f}] | {a2['pt']:+.3f} [{a2['lo']:+.3f}, {a2['hi']:+.3f}] | {a3['pt']:+.3f} [{a3['lo']:+.3f}, {a3['hi']:+.3f}] | {best['pt']:+.3f} [{best['lo']:+.3f}, {best['hi']:+.3f}] |")
        rec.add(f"d1_minus_p1.p{int(lvl * 100)}", a1["pt"], "fraction", f"loss level {lvl}")
        rec.add(f"d1_minus_p4.p{int(lvl * 100)}", a2["pt"], "fraction", f"loss level {lvl}")
        rec.add(f"d1_minus_quick.p{int(lvl * 100)}", a3["pt"], "fraction", f"loss level {lvl}")
    cnt = Counter(E.best_baseline(res[c], "deadline") for c in names)
    L.append("\nBest baseline per cell (by mean delivery before the deadline): " + ", ".join(f"{k} in {n} cells" for k, n in cnt.most_common()) + ".\n")
    for k, n in cnt.items():
        rec.add(f"best_baseline_cells.{k}", int(n), "cells", "number of cells in which this baseline is the best of the six")
    # --- D2 cost
    air_d1 = np.mean([res[c]["D1"]["runs"][:, 4].mean() for c in burst])
    air_d2 = np.mean([res[c]["D1D2"]["runs"][:, 4].mean() for c in burst])
    nsh1 = np.mean([res[c]["D1"]["runs"][:, 2].mean() for c in burst])
    nsh2 = np.mean([res[c]["D1D2"]["runs"][:, 2].mean() for c in burst])
    col1 = np.mean([res[c]["D1"]["runs"][:, 5].mean() for c in burst])
    col2 = np.mean([res[c]["D1D2"]["runs"][:, 5].mean() for c in burst])
    rec.add("d2.cluster_ack_air_s_per_burst_hour", float(air_d2), "s", "mean gateway airtime of cluster ACKs per simulated hour in the burst cells (D1 has none)")
    rec.add("d2.collided_share_d1", float(col1), "fraction", "collided share of alert transmissions, burst cells, D1")
    rec.add("d2.collided_share_d1d2", float(col2), "fraction", "same, D1 plus D2")
    L.append("## 4. What D2 cost and changed in the burst cells (descriptive)\n")
    L.append(f"Gateway airtime spent on cluster ACKs: {air_d2:.1f} s per simulated hour (D1 has none: {air_d1:.1f}). Vehicle airtime share of the allowance: D1 {nsh1:.3f}, D1+D2 {nsh2:.3f}. Collided share of alert transmissions: D1 {col1:.3f}, D1+D2 {col2:.3f}. "
             "A 64-byte signature makes each cluster ACK about as long as an alert, and the gateway cannot receive while it sends, so a large part of the benefit of earlier stops is paid for in gateway deafness (inferred from these counts; not isolated).\n")
    # --- DEV record
    L.append("## 5. Development record (DEV grid, new seeds; at most 5 iterations per algorithm)\n")
    L.append("| Algorithm | Iteration | Change | Key DEV metric |\n|---|---|---|---|")
    for row in csv.DictReader(open("results/tables/rd_dev_log.csv", encoding="utf-8")):
        m = json.loads(row["metrics"])
        key = f"mean gain over the severity table {m['mean_gain_vs_P1']:+.3f}, smallest cell {m['min_cell_gain']:+.3f}" if row["algo"] == "D1" else f"burst gain {m['burst_mean_gain_crit10']:+.3f}, smallest cell final {m['min_cell_final_diff']:+.4f}"
        L.append(f"| {row['algo']} | {row['iteration']} | {row['note']} | {key} |")
    L.append("\nChosen by the preregistered objective: D1 iteration 2, D2 iteration 4. After the pre-freeze code fixes the chosen parameters were re-run on DEV as a check (`results/tables/rd_dev_checks.csv`), not as an iteration.\n")
    # --- caveats
    L.append("## 6. Reading with care\n")
    for t in ("These are results of the custom simulator only. The cross-simulator check (ns-3 lorawan, X1) is run separately; until D1 is also checked there, D1 is not placed in the main paper and its result is described as simulator-dependent in principle.",
              "The severity table is a weak baseline in this simulator (it waits 5 s before the initial Critical send and retries without spacing). The gain over the best of six baselines is small (mean +0.03; the smallest cell is slightly negative but within the bound). Most of D1's gain over the table is also available from quick retries with a spreading-factor raise; D1 adds a duty-cycle budget, a load index and a loss estimate, and the check against quick retries is in section 3.",
              "D1's table uses the simulator's own spreading-factor decay (0.7 per step). A real channel may differ; the ns-3 check tests another physical model.",
              "Absence statements: no study with a gateway-signed aggregated ACK for LoRa alert bursts was found in the sources checked (web search; IEEE Xplore, Scopus, Google Scholar and TRID not run); `docs/06_references/CLOSEST_PRIOR_WORK.md`.",
              "DEV and FRESH-A share the finite pool of real class pairs and decision times (addendum A, 5f). The FRESH-A grid is new in arrivals, channel draws, geometry and cell parameters."):
        L.append(f"- {t}")
    rec.write()
    Path("docs/03_results/REDESIGN_A_RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("written")


if __name__ == "__main__":
    main()
