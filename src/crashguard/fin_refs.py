"""D4: list every reference of docs/06_references/REFERENCES.md with an unverified field (generated) and append the finishing-branch sources to docs/06_references/REFERENCES.md."""
from __future__ import annotations

import re
from pathlib import Path

START, END = "<!-- finish:start -->", "<!-- finish:end -->"


def main() -> None:
    p = Path("docs/06_references/REFERENCES.md")
    t = p.read_text(encoding="utf-8")
    t = t[: t.index(START)] if START in t else t
    rows = [ln for ln in t.splitlines() if ln.startswith("| ") and "NOT VERIFIED" in ln]
    named = []
    for ln in rows:
        cells = [c.strip() for c in ln.strip("|").split("|")]
        named.append((cells[0], cells[1][:90], len(re.findall("NOT VERIFIED", ln))))
    lines = ["# References whose fields are unverified (generated by `crashguard.fin_refs`)", "",
             "A field is verified only if it appeared on a page that was opened. The list below has every row of `docs/06_references/REFERENCES.md` that contains the words NOT VERIFIED, with the number of unverified fields. **Fill these by hand from the publisher pages before submission.**", "",
             "## Named works that could not be opened (no number of theirs is used)", "",
             "- Jao and Shkel 2022 (triangular-function reconstruction with Gaussian-process regression): not found by search on 2026-11-11, 2026-11-12.",
             "- Zhang et al. 2026 (peak-aware saturation compensation): not found by search.",
             "- Wusk and Gabler, 25th ESV, paper 25-0407: only a TRID search listing was seen; the page was not fetched.",
             "- Carvalho et al. 2021 (LoRaWAN redundancy for emergency traffic) and Chen et al., GLOBECOM 2023: could not be opened.",
             "- Semtech time-on-air document (AN1200.13 or the SX1276 datasheet): the semtech.com address redirected to a page without documents and the Mouser copy timed out twice on 2026-11-13; airtime is tested against the formula as transcribed only.", "",
             "## Rows with unverified fields", "", "| Key | Entry (start) | Unverified fields |", "|---|---|---|"]
    lines += [f"| {k} | {n} | {c} |" for k, n, c in named]
    Path("docs/06_references/REFERENCES_UNVERIFIED.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    add = [START, "", "## Finishing branch (2026-11-13)", "",
           "| Key | Source | Opened | Use |", "|---|---|---|---|",
           "| F-R1 | IEEEtran.cls V1.8b (2015/08/26), CTAN mirror https://mirrors.ctan.org/macros/latex/contrib/IEEEtran/IEEEtran.cls | 2026-11-13 (downloaded) | paper class file in `paper/`; LPPL; no TeX distribution was available to compile |",
           "| F-R2 | Semtech time-on-air formula (AN1200.13 / SX1276 datasheet) | NOT opened (redirect; two timeouts) | none; `lora.airtime_ms` is tested against the formula as transcribed |",
           "| F-R3 | VZCrash dataset, Hugging Face revision 42e1482d005c0e545379d6cfa4939486c9fe4249 | user-supplied statement 2026-11-12 (author reply): CC BY-NC 4.0, the downloaded copy corresponds to this revision, identifiers or hashes may be cited | licence statement; not independently verified here |",
           "| F-R4 | data.gov catalogue entry for the NHTSA Vehicle Crash Test Database | opened earlier (rights field reads \"public\"); nhtsa.gov terms pages returned HTTP 403 | NHTSA terms are not verified |", "",
           "Unverified fields of other entries: `docs/06_references/REFERENCES_UNVERIFIED.md`.", END]
    p.write_text(t.rstrip("\n") + "\n\n" + "\n".join(add) + "\n", encoding="utf-8")
    print(len(named), "rows with unverified fields")


if __name__ == "__main__":
    main()
