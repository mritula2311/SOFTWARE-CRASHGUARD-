"""SUPERSEDED 2026-11-13 by the index in docs/README.md; kept only as a record. It is no longer part of `make report`.
Reason: the combined file duplicated every document and went stale after each edit.

Combine every docs/*.md into docs/archive/ALL_DOCS_COMBINED.md (originals are kept: code reads and rewrites some of them)."""
from pathlib import Path

docs = sorted(p for p in Path("docs").glob("*.md") if p.name != "ALL_DOCS_COMBINED.md")
out = ["# All documentation, combined", "", "Generated by `python scripts/combine_docs.py` after the final run. The originals in `docs/` remain the source files.", "", "## Contents", ""]
out += [f"- {p.name}" for p in docs]
for p in docs:
    out += ["", "---", "", f"# FILE: {p.name}", "", p.read_text(encoding="utf-8").rstrip()]
Path("docs/archive/ALL_DOCS_COMBINED.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(len(docs), "files combined")
