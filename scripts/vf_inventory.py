"""V0: write docs/04_audits/INVENTORY.md (branches, tags, preregistrations, result-key prefixes, release zips, docs)."""
import collections
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def git(*a):
    return subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def main():
    out = []
    out.append("# Inventory (V0)\n")
    out.append("<!-- header:start -->\n| Field | Value |\n|---|---|\n| Status | current |\n| Date | 2026-11-15 |\n| Owner | Mritula S |\n| Scope | Branches, tags, preregistrations, result keys, release files and documents at the start of the verification run (generated by scripts/vf_inventory.py). |\n| Evidence labels used | none (this file reports no result) |\n| Abbreviations | SHA = secure hash algorithm |\n<!-- header:end -->\n")
    out.append("## Branches\n")
    out.append("| Branch | Commit | Subject |\n|---|---|---|")
    for line in git("branch", "--format=%(refname:short)|%(objectname:short)|%(subject)").splitlines():
        b, c, s = line.split("|", 2)
        out.append(f"| {b} | {c} | {s} |")
    out.append("\n## Tags\n")
    out.append("| Tag | Object type | Peeled commit | Subject of the commit | Archive comment (git archive) | Match |\n|---|---|---|---|---|---|")
    import zipfile
    zc = {}
    for z in (ROOT / "release").glob("crashguard-*.zip"):
        zc[z.stem.replace("crashguard-", "")] = zipfile.ZipFile(z).comment.decode("ascii", "replace")
    for t in git("tag", "-l").splitlines():
        typ = git("cat-file", "-t", t)
        full = git("rev-parse", t + "^{commit}")
        subj = git("log", "-1", "--format=%s", full)
        if t not in zc:
            arc, match = "", "no archive"
        elif not zc[t]:
            arc, match = "", "archive carries no commit id"
        else:
            arc = zc[t]
            match = "yes" if arc == full else "NO"
        out.append(f"| {t} | {typ} | {full[:7]} | {subj[:90]} | {arc[:7]} | {match} |")
    out.append("\n## Preregistration files\n")
    out.append("| File | Size (bytes) | Title line |\n|---|---|---|")
    for p in sorted((ROOT / "docs/02_preregistration").glob("*.md")):
        first = p.read_text(encoding="utf-8", errors="replace").splitlines()[0]
        out.append(f"| {p.name} | {p.stat().st_size} | {first} |")
    # addenda inside V16 and other files
    out.append("\nAddenda found by heading search (`Addendum`) in preregistration and decision files:\n")
    for p in sorted((ROOT / "docs").rglob("*.md")):
        if "archive" in p.parts:
            continue
        txt = p.read_text(encoding="utf-8", errors="replace")
        hs = [ln.strip() for ln in txt.splitlines() if re.match(r"^#+\s.*[Aa]ddendum", ln)]
        if hs and "02_preregistration" in str(p):
            for h in hs:
                out.append(f"- {p.relative_to(ROOT)}: {h}")
    out.append("\n## results.json keys by prefix\n")
    r = json.load(open(ROOT / "results/results.json", encoding="utf-8"))
    c = collections.Counter(e["name"].split(".")[0] for e in r)
    lab = collections.Counter(e.get("origin") for e in r)
    out.append(f"Total entries: {len(r)}\n")
    out.append("| Prefix | Entries |\n|---|---|")
    for k, v in sorted(c.items(), key=lambda x: -x[1]):
        out.append(f"| {k} | {v} |")
    out.append("\n| Origin label | Entries |\n|---|---|")
    for k, v in sorted(lab.items(), key=lambda x: -x[1]):
        out.append(f"| {k} | {v} |")
    out.append("\n## Release files\n")
    out.append("| File | Bytes | SHA-256 | In git? |\n|---|---|---|---|")
    tracked = set(git("ls-files", "release").splitlines())
    for p in sorted((ROOT / "release").glob("*.zip")):
        out.append(f"| {p.name} | {p.stat().st_size} | {sha(p)} | {'yes' if 'release/' + p.name in tracked else 'no'} |")
    out.append("\n## Documents under docs/ (non-archive)\n")
    byd = collections.defaultdict(list)
    for p in sorted((ROOT / "docs").rglob("*")):
        if p.is_file() and "archive" not in p.parts and "literature" not in p.parts:
            byd[str(p.parent.relative_to(ROOT))].append(p.name)
    for d, fs in byd.items():
        out.append(f"- **{d}** ({len(fs)}): " + ", ".join(fs))
    (ROOT / "docs/04_audits/INVENTORY.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("written", len(out), "lines")


if __name__ == "__main__":
    main()
