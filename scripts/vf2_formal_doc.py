"""D2.1: record the rerun of the round-6 formal models: copy the rerun outputs of the fresh clone to formal/rerun_vf2/ and write docs/04_audits/DELTA_FORMAL_RERUN.md (stored against rerun verdicts, times, memory).

    python scripts/vf2_formal_doc.py <clone root>
"""
from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
clone = Path(sys.argv[1])
SRC_DIR, NEW_DIR = ROOT / "formal" / "out" / "r6", clone / "formal" / "out" / "r6"
KEEP = ROOT / "formal" / "rerun_vf2"
KEEP.mkdir(exist_ok=True)
NAMES = [("pv_micro_confirm", "ProVerif 2.05", "R6-1c: micro-confirm authenticity, binding to the flash, micro-cancel"), ("pv_micro_confirm_control", "ProVerif 2.05", "R6-1c control: tag without the provisional tag (attack expected)"),
         ("tam_micro_confirm", "Tamarin 1.12.0", "R6-1c: same properties"), ("tam_micro_confirm_control", "Tamarin 1.12.0", "R6-1c control (attack expected)"),
         ("pv_ratchet_auth", "ProVerif 2.05", "R6-3a: authenticity of past alerts under a hash ratchet, 3 steps"), ("pv_ratchet_secrecy", "ProVerif 2.05", "R6-3a: secrecy of past alerts after the current key is revealed, 3 steps")]


def verdicts(p: Path) -> list[str]:
    t = p.read_text(encoding="utf-8", errors="replace").replace(chr(13), "")
    out = [f"Q{i + 1}={m.group(2)}" for i, m in enumerate(re.finditer(r"^Query (.*) is (true|false)\.$", t, re.M))]
    for m in re.finditer(r"^\s+(\w+) \((?:all|exists)-traces?\): (verified|falsified)", t, re.M):
        out.append(f"{m.group(1)}={m.group(2)}")
    return out


def meta(p: Path) -> str:
    m = re.search(r"exit code: (\d+) ; wall time (\d+) s ; peak memory (\d+) MB", p.read_text(encoding="utf-8", errors="replace"))
    return f"{m.group(2)} s, {m.group(3)} MB" if m else "?"


rows = []
same = 0
for n, tool, what in NAMES:
    a, b = SRC_DIR / f"{n}.txt", NEW_DIR / f"{n}.txt"
    shutil.copy(b, KEEP / b.name)
    va, vb = verdicts(a), verdicts(b)
    same += int(va == vb)
    rows.append(f"| {what} | {tool} | {', '.join(va)} | {', '.join(vb)} | {'yes' if va == vb else 'NO'} | {meta(a)} | {meta(b)} |")
