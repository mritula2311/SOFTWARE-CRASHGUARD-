"""Round 5 audit: frozen hashes intact, held-out keys present once, labels valid, earlier keys unchanged, every verdict traceable. Writes docs/04_audits/R5_CLAIM_AUDIT.md.

    python scripts/r5_audit.py
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from crashguard import r5_common as R5  # noqa: E402
from crashguard.results import ORIGINS  # noqa: E402

HELD = {"l1": "r5.l1.hL1.criterion_met", "l2": "r5.l2.hL2a.criterion_met", "l3": "r5.l3.hL3.criterion_met", "l4": "r5.l4.ns3.hL4.ns3.criterion_met", "l5": "r5.l5.hL5.criterion_met", "l6": "r5.l6.hL6.criterion_met",
        "l7": "r5.l7.hL7b.criterion_met", "l8": "r5.l8.hL8a.criterion_met", "l9": "r5.l9.rho.act_vs_wait", "l10": "r5.l10.hL10a.criterion_met", "l11": "r5.l11.hL11a.criterion_met"}


CRLF, LF = bytes([13, 10]), bytes([10])


def same_hash(p: Path, h: str) -> bool:
    """True if the file has the frozen SHA-256 as stored, or with CRLF read as LF, or with LF read as CRLF (a Windows checkout rewrites line endings; the frozen hashes were taken on the author's working copy, where both endings occur)."""
    b = p.read_bytes()
    lf = b.replace(CRLF, LF)
    return h in {hashlib.sha256(x).hexdigest() for x in (b, lf, lf.replace(LF, CRLF))}


def main() -> int:
    res = json.loads((ROOT / "results" / "results.json").read_text(encoding="utf-8"))
    by = {e["name"]: e for e in res}
    frozen = json.loads(R5.FROZEN.read_text(encoding="utf-8"))
    problems, lines = [], []
    for name, d in sorted(frozen.items()):
        bad = [f for f, h in {**d["files"], **d.get("data", {})}.items() if not same_hash(ROOT / f, h)]
        # sources shared by several freezes may legitimately change after an earlier algorithm was run; they are listed, not hidden
        lines.append(f"| {name} | {d['git_head'][:8]} | {len(d['files'])} | {len(d.get('data', {}))} | {', '.join(bad) or 'none'} |")
        if bad and name in ("l6", "l7", "l8", "l9", "l10", "l11"):
            problems.append(f"{name}: frozen file changed after the freeze: {bad}")
    for alg, key in HELD.items():
        if key not in by:
            problems.append(f"{alg}: result key {key} missing")
    r5 = [e for e in res if e["name"].startswith("r5.")]
    badlab = [e["name"] for e in r5 if e["origin"] not in ORIGINS]
    nrun = [e["name"] for e in r5 if e["origin"] == "NOT_RUN" and not str(e.get("notes", "")).strip()]
    if badlab or nrun:
        problems.append(f"labels: {badlab[:3]} NOT_RUN without reason: {nrun[:3]}")
    k = subprocess.run([sys.executable, str(ROOT / "scripts" / "verify_keys_unchanged.py")], capture_output=True, text=True, cwd=ROOT).stdout.strip().splitlines()[-1]
    if " 0 changed or missing" not in k:
        problems.append("earlier keys changed: " + k)
    out = ["# Round 5 claim audit", "", "<!-- header:start -->", "<!-- header:end -->", "",
           "Generated by `scripts/r5_audit.py`. Checks: the frozen hashes of every round-5 algorithm (the list below names any frozen file that differs now; shared sources such as `r5_common.py` can differ for the algorithms frozen in session 1 and are listed, not hidden); the held-out key of every algorithm exists; every `r5.` label is valid and every NOT_RUN has a reason; earlier keys are unchanged.", "",
           "| Algorithm | Frozen at commit | Source files | Data files | Frozen files that differ now |", "|---|---|---:|---:|---|"] + lines + ["", f"Earlier keys: {k}", f"Round-5 keys: {len(r5)}.", "", "**Result: " + ("no problem found." if not problems else "problems: " + "; ".join(problems)) + "**", ""]
    (ROOT / "docs" / "04_audits" / "R5_CLAIM_AUDIT.md").write_text("\n".join(out), encoding="utf-8")
    print(k)
    print("problems:", problems or "none")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
