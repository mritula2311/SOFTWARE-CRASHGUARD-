"""D6.1: write docs/04_audits/FINALIZE_LATEX_LINT.md from the Tectonic compile of scripts/vf_shim_compile.py (page counts, overfull boxes, undefined references) and the structure counts of main.tex.

    python scripts/vf2_latex_doc.py <work dir of vf_shim_compile.py>
"""
import re
import sys
from pathlib import Path

import pypdf

ROOT = Path(__file__).resolve().parents[1]
work = Path(sys.argv[1])
main = (ROOT / "paper" / "main.tex").read_text(encoding="utf-8")
rows = []
for name in ("main_shim", "supplement", "supplement_full"):
    pdf, log = work / f"{name}.pdf", work / f"{name}.log"
    pages = len(pypdf.PdfReader(str(pdf)).pages)
    t = log.read_text(encoding="utf-8", errors="replace")
    over = [float(x) for x in re.findall(r"Overfull \\hbox \(([\d.]+)pt too wide", t)]
    und = len(re.findall(r"(Citation|Reference|Label).{0,40}undefined", t, re.I))
    errs = len(re.findall(r"^!", t, re.M))
    rows.append((name, pages, len(over), max(over) if over else 0.0, und, errs))
nfig = len(re.findall(r"\\includegraphics", main))
ntab = len(re.findall(r"\\begin\{table\*?\}", main))
L = ["# LaTeX lint and compile check (finalize F4.3)", "", "<!-- header:start -->", "<!-- header:end -->", "",
     "Generated by `python scripts/vf2_latex_doc.py`. Engine: Tectonic 0.15.0 (user-level, XeTeX). The IEEE Access class `ieeeaccess.cls` cannot be run by Tectonic (it uses pdfTeX primitives), so `main.tex` is compiled with the class IEEEtran and shims for the Access-only commands "
     "(`scripts/vf_shim_compile.py`); the page count of the main text is therefore an estimate. The supplements are compiled with their own class (article).", "",
     "| File | Pages | Overfull boxes | Widest overfull (pt) | Undefined references or citations | Errors |", "|---|---:|---:|---:|---:|---:|"]
for name, pages, n, w, u, e in rows:
    L.append(f"| {name} | {pages} | {n} | {w:.1f} | {u} | {e} |")
L += ["", f"Main text: {nfig} figures and {ntab} tables (limits: 8 and 8). `supplement` is the reduced supplement of the submission; `supplement_full` is the full one that goes into the release archive under `supplementary_full/`.", "",
      "## Likely Overleaf errors, in order of likelihood", "",
      "| Rank | Place | Problem | Fix |", "|---|---|---|---|",
      "| 1 | `main.tex` line 4 | the Overleaf copy of `ieeeaccess.cls` may be older than the 2026-05-13 template; `\\titlepgskip` differs between versions | upload the class of the current template next to `main.tex`; adjust `\\titlepgskip` if the title page is cut |",
      "| 2 | `main.tex`, ledger table | the ledger table has seven columns in one column of the two-column page (set in `\\footnotesize`, leading column `p{2.3cm}`); an overfull box can still appear in the class's narrower column | shorten the row labels or move the table to `table*`; accept an overfull warning |",
      "| 3 | `main.tex`, sections C4 and C5 | inline math with macros (`$T_F=$ \\DutyDue{} s`, `$A_f \\le d\\,(T_F - s_f)$`): fails only if `numbers.tex` is not uploaded | upload `paper/generated/numbers.tex` and keep the folder structure |",
      "| 4 | `supplement.tex` | `\\path{...}` (package `url`) and `\\texttt{...}` in the archive list; the long paths do not break in `\\texttt` | none needed; they are warnings (overfull boxes), not errors |",
      "| 5 | `supplement.tex`, generated tables | about 370 overfull-box warnings from wide Markdown tables (the full supplement about 1,100) | accept; Overleaf shows them as warnings |",
      "| 6 | figures | all 8 figure files exist under `paper/figures/` | upload the whole `paper/` folder |",
      "| 7 | `references.bib` | 51 entries (one added in the finalize run: `gsr347`); `IEEEtran.bst` is in the template; the long URL of `gsr347` gives one overfull warning of about 40 pt in the reference list | none needed (a warning) |",
      "| 8 | `\\EOD` and `keywords` | defined by the Access class | none |", ""]
(ROOT / "docs" / "04_audits" / "FINALIZE_LATEX_LINT.md").write_text("\n".join(L), encoding="utf-8")
print(rows, nfig, ntab)
