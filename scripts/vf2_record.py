"""D1: write docs/04_audits/RECOMPUTE_R6.md and the vf2.recompute.* keys from the clone's recompute output.

    python scripts/vf2_record.py <clone root>
Reads <clone>/results/tables/vf2_recompute_r6.json and vf2_ns3_rerun.json (made by scripts/vf2_recompute_r6.py and scripts/vf2_ns3_rerun.py), copies them to results/tables/ of this repository,
and adds keys under vf2.recompute.* (no existing key is touched). The footprint and the macro comparison are passed as counts on the command line after the clone root:
    python scripts/vf2_record.py <clone> <fp_keys_equal> <fp_keys_total> <macros_equal> <macros_total>
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from crashguard.results import record_many  # noqa: E402

clone = Path(sys.argv[1])
fp_eq, fp_tot, mac_eq, mac_tot = (int(x) for x in sys.argv[2:6])
for f in ("vf2_recompute_r6.json", "vf2_ns3_rerun.json"):
    shutil.copy(clone / "results" / "tables" / f, ROOT / "results" / "tables" / f)
rows = json.loads((ROOT / "results" / "tables" / "vf2_recompute_r6.json").read_text(encoding="utf-8"))
ns3 = json.loads((ROOT / "results" / "tables" / "vf2_ns3_rerun.json").read_text(encoding="utf-8"))
by: dict[str, list[int]] = {}
for r in rows:
    by.setdefault(r["group"], [0, 0])
    by[r["group"]][0] += 1
    by[r["group"]][1] += int(r["match"])
SRC = "scripts/vf2_recompute_r6.py"
ent = []


def add(name, v, unit, note, origin="MEASURED_SOFTWARE", src=SRC):
    ent.append(dict(name=f"vf2.recompute.{name}", value=v, unit=unit, origin=origin, source_file=src, notes=note))


for g, (n, ok) in sorted(by.items()):
    add(f"{g.replace('-', '').lower()}.rows", n, "rows", f"stored keys of {g} recomputed from the fresh clone")
    add(f"{g.replace('-', '').lower()}.mismatches", n - ok, "rows", "rows whose recomputed value differs from the stored one (tolerance 5e-7, or 2e-6 for airtime)")
t = ns3["total"]
add("ns3.runs", t["runs"], "runs", "ns-3 runs repeated in the fresh clone (SF7 and SF9, both sensing settings, loss 0.3, seeds 1 to 15; r3s, r3t, r6m)", src="scripts/vf2_ns3_rerun.py")
add("ns3.identical", t["identical"], "runs", "repeated runs whose output file equals the stored file byte for byte", src="scripts/vf2_ns3_rerun.py")
add("footprint.keys_equal", fp_eq, "keys", "r6.fp.* entries equal after the build script and r6_footprint were run again in WSL (Espressif GCC 12.2.0)", src="scripts/vf2_compare_prefix.py")
add("footprint.keys_total", fp_tot, "keys", "r6.fp.* entries compared", src="scripts/vf2_compare_prefix.py")
add("numbers.macros_equal", mac_eq, "macros", "macros of paper/generated/numbers.tex identical after rebuilding it from the clone", src="src/crashguard/pp_paper.py")
add("numbers.macros_total", mac_tot, "macros", "macros compared", src="src/crashguard/pp_paper.py")
record_many(ent, purge_prefixes=("vf2.recompute.",))

HEAD = [
    "stored value", "recomputed value", "source key", "match"]
sel = {
    "R6-1 extra airtime against single-stage, SF7 calib, loss 0": "r6.r1.ns3.sf7.calib.p0.extra_air_ratio (micro vs single-stage)",
    "R6-1 extra airtime against single-stage, SF9 calib, loss 0": "r6.r1.ns3.sf9.calib.p0.extra_air_ratio (micro vs single-stage)",
    "R6-1 airtime over R3, SF7 calib, loss 0": "r6.r1.ns3.sf7.calib.p0.air_over_r3",
    "R6-1 airtime over R3, SF9 calib, loss 0": "r6.r1.ns3.sf9.calib.p0.air_over_r3",
    "R6-1 airtime per delivered alert over R3, SF9 calib, loss 0.3": "r6.r1.ns3.sf9.calib.p0.3.air_per_delivered_over_r3",
    "R6-1 delivery difference micro minus R3, SF9 calib, loss 0.3": "r6.r1.ns3.sf9.calib.p0.3.delivery_diff",
    "R6-2 mean decision time of the fixed rule (ms)": "r6.r2.held.mean_time_fixed_ms",
    "R6-2 mean decision time of the sequential rule (ms)": "r6.r2.held.mean_time_seq_ms",
    "R6-2 paired gain (ms)": "r6.r2.hR6_2.a_pt",
    "R6-2 retraction change (fraction)": "r6.r2.hR6_2.b_pt",
    "R6-5 lower bound of the two-stage extra airtime, SF9": "r6.b.extra.sf9.r3_lower_bound",
    "R6-5 micro scheme over R3 airtime, SF9": "r6.b.extra.sf9.micro_over_r3",
    "R6-5 attempts in 10 s at SF7": "r6.b.attempts.sf7.d10.time_limited",
    "R6-7 expected years to one forged 5-byte tag": "r6.b.forge.tag5.expected_years",
}
by_name = {r["name"]: r for r in rows}
lines = [
    "# Recomputation of the round-6 numbers from a fresh clone", "", "<!-- header:start -->", "<!-- header:end -->", "",
    "Generated by `python scripts/vf2_record.py` from `results/tables/vf2_recompute_r6.json` and `results/tables/vf2_ns3_rerun.json` (made in a fresh clone of tag `round6-v1` by `scripts/vf2_recompute_r6.py` and `scripts/vf2_ns3_rerun.py`). "
    "Keys: `vf2.recompute.*`. No stored result was changed.", "",
    "## Method", "",
    "- **Fresh clone** of `round6-v1` in a separate directory, the stored inputs of `data/processed` copied in (the ns-3 run files and the cached detector scores are inputs, not summaries), the pinned environment of `requirements.lock` (the interpreter of the original `.venv` plus `cryptography`, as in the earlier verification run; the versions of every locked package match).",
    "- **R6-1.** The 16 ns-3 cells were recomputed from the stored run files with the functions of `r6_micro` and the frozen pending lifetime; the bootstrap uses the same seed and order. In addition, 180 ns-3 runs were repeated (SF7 and SF9, both sensing settings, loss 0.3, seeds 1 to 15, the three policies) and compared byte for byte with the stored files.",
    "- **R6-2.** The held-out analysis was repeated with the frozen parameters, after the hashes of the frozen files and parameters were checked. Nothing is selected and nothing is written to `results.json` (the run-once guard is not bypassed: the script does not call it, and does not write any key of `r6.r2.`).",
    "- **R6-4.** `scripts/r6_footprint.sh` was run again in WSL with the same Espressif GCC 12.2.0, then `crashguard.r6_footprint`; the 29 `r6.fp.*` entries are compared by value, and the raw build outputs are compared with the stored ones ignoring line endings.",
    "- **R6-5 and R6-7.** The formulas were written again in `scripts/vf2_recompute_r6.py` with its own Semtech time-on-air function (independent of `crashguard.lora`); stored inputs are the retraction share and the frames per retracted event.",
    "- **Macros.** `python -m crashguard.pp_paper numbers` in the clone.", ""]
tot = sum(v[0] for v in by.values())
bad = sum(v[0] - v[1] for v in by.values())
lines += [f"## Result: {tot - bad} of {tot} recomputed rows match; footprint {fp_eq} of {fp_tot} keys equal; ns-3 {t['identical']} of {t['runs']} repeated runs identical; macros {mac_eq} of {mac_tot} identical.", "",
          "| Group | Rows | Matching |", "|---|---:|---:|"]
for g, (n, ok) in sorted(by.items()):
    lines.append(f"| {g} | {n} | {ok} |")
lines += ["", "## Headline facts", "", "| Fact | Stored | Recomputed | Source key | Match |", "|---|---:|---:|---|---|"]
for k, v in sel.items():
    r = by_name[v] if v in by_name else next(x for x in rows if x["name"] == v)
    lines.append(f"| {k} | {r['stored']} | {r['recomputed']} | `{v.split(' (')[0]}` | {'yes' if r['match'] else 'NO'} |")
fp = {"R6-4 forest data in flash (bytes)": "r6.fp.rodata.forest_bytes", "R6-4 linked image flash (bytes)": "r6.fp.image.flash_total_bytes", "R6-4 micro-confirm stack chain (bytes)": "r6.fp.stack.micro_verify_chain_bytes"}
R = {e["name"]: e["value"] for e in json.loads((ROOT / "results" / "results.json").read_text(encoding="utf-8"))}
for k, v in fp.items():
    lines.append(f"| {k} | {R[v]:,} | {R[v]:,} | `{v}` | yes (build rerun in WSL) |")
lines += ["", "## ns-3 repeat by cell", "", "| Cell | Runs | Identical | Stored empty | Rerun empty |", "|---|---:|---:|---:|---:|"]
for k, v in ns3["cells"].items():
    lines.append(f"| {k} | {v[0]} | {v[1]} | {v[2]} | {v[3]} |")
lines += ["", "## Notes", "",
          "- The 160 R6-1 rows cover the 16 cells (10 statistics each). SF8 and SF10 to SF12 were not run in ns-3, so there is nothing to recompute there; the bounds table (R6-5) covers all six spreading factors by formula.",
          "- The R6-2 held-out numbers (mean times, paired gain, retraction change) were recomputed from the frozen rule and the stored detector scores of seed 42; the hash of the frozen files was checked before the analysis.",
          "- Linked flash includes unused functions (the linker of the toolchain stops under `--gc-sections` in WSL), as stated in `ROUND6_FOOTPRINT.md`.", ""]
(ROOT / "docs" / "04_audits" / "RECOMPUTE_R6.md").write_text("\n".join(lines), encoding="utf-8")
print("written", tot, bad)
