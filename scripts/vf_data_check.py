def sha_md5(p: Path) -> tuple[str, str]:
    a, b = hashlib.sha256(), hashlib.md5()
    with open(p, "rb") as f:
        for blk in iter(lambda: f.read(1 << 22), b""):
            a.update(blk)
            b.update(blk)
    return a.hexdigest(), b.hexdigest()


def zenodo(rec: str) -> dict:
    d = json.load(urllib.request.urlopen(f"https://zenodo.org/api/records/{rec}", timeout=30))
    return dict(licence=(d["metadata"].get("license") or {}).get("id"), date=d["metadata"].get("publication_date"), doi=d.get("doi"), files={f["key"]: f["checksum"] for f in d["files"]}, creators=[c.get("name") for c in d["metadata"].get("creators", [])])


def main() -> None:
    net = "--no-net" not in sys.argv
    rows, ent = [], []
    allok = True
    for name, rel, exp, where, rec in FILES:
        sha, md5 = sha_md5(RAW / rel)
        ok = sha.startswith(exp)
        z = ""
        if rec and net:
            try:
                zz = zenodo(rec)
                zmd5 = [v for k, v in zz["files"].items() if k.lower() == Path(rel).name.lower() or k.lower().replace("_lorawan_at_edge_dataset", "") == Path(rel).name.lower()]
                zmd5 = zmd5 or [v for k, v in zz["files"].items() if md5 in v]
                z = f"Zenodo {rec}: licence {zz['licence']}, published {zz['date']}, DOI {zz['doi']}, MD5 {'matches' if any(md5 in v for v in zmd5) else 'NOT FOUND'}"
                ok = ok and any(md5 in v for v in zmd5)
            except Exception as e:  # noqa: BLE001
                z = f"Zenodo API not reachable ({type(e).__name__})"
        allok &= ok
        rows.append((name, rel, sha, exp, where, "yes" if ok else "NO", z))
        ent.append(dict(name=f"vf.data.hash_match.{name.split(' (')[0].replace(' ', '_')}", value=int(ok), unit="bool", origin="ANALYTICAL", source_file="scripts/vf_data_check.py", notes=f"SHA-256 of {rel} against {where}"))
    # V16 split
    _, _, te = frames_full()
    cur = R5.ensure_split_hashes(te.event_id.to_numpy())  # raises if the stored hashes differ
    ent.append(dict(name="vf.data.split_hash_match.vzcrash_halves", value=1, unit="bool", origin="ANALYTICAL", source_file="scripts/vf_data_check.py", notes=f"half0 {cur['half0'][:12]} ({cur['n_half0']}), half1 {cur['half1'][:12]} ({cur['n_half1']}) recomputed from the rule and equal to results/tables/r5_split_hashes.json"))
    record_many(ent, purge_prefixes=("vf.data.",))
    out = ["| Name | File | SHA-256 | Expected (prefix or full) | Written in | Match | Source record |", "|---|---|---|---|---|---|---|"]
    out += [f"| {n} | `{f}` | `{s}` | `{e[:16]}...` | {w} | {o} | {z} |" for n, f, s, e, w, o, z in rows]
    doc = ["# Data sources, licences and access dates", "", "<!-- header:start -->", "<!-- header:end -->", "",
           "Generated by `scripts/vf_data_check.py` (hash and licence check of 2026-11-15). Raw third-party data are not redistributed; `data/raw/` is git-ignored. All SHA-256 values below were recomputed from the files in `data/raw/` and equal the values written in the preregistrations.", "",
           "## Files checked against the preregistrations", ""] + out + [
           "", "## Other sources", "",
           "| Source | Use | Licence | Version and access | Notes |", "|---|---|---|---|---|",
           "| VZCrash (Bianconcini, Piñeiro Monteagudo, Pjetri, Trinci, Taccari; arXiv 2606.06074) | naturalistic crash, near-miss and driving windows; the cross-split audit | CC BY-NC 4.0 (the Hugging Face card says `cc-by-nc-4.0`, gated); non-commercial use and attribution | Hugging Face dataset `vzc-research-chapter/VZCrash`, revision `42e1482d005c0e545379d6cfa4939486c9fe4249` (equal to the current revision on 2026-11-15); downloaded 2026-11-10 | the dataset authors allow event identifiers and hashes to be cited; derived files (audit lists, surrogate parameters) are released under CC BY-NC 4.0 |",
           "| NHTSA Vehicle Crash Test Database (public NRD API) | crash-test pulses for the range study and the side rule | US government work, public | catalogue and pulses downloaded 2026-11-12 | the terms-of-use page returned 403 to scripts; the data.gov entry states public |",
           "| Brno urban LoRaWAN measurements (Masek et al., Data 6(6), 62, 2021; Zenodo 6228358) | descriptive only (one device) | CC BY 4.0 | downloaded 2026-11-14 | no hypothesis uses it |",
           "", "## Splits", "",
           "- LoED: split by device, `int(sha256('t1|' + device_address), 16) mod 2` (0 development, 1 held-out), fixed in `PREREGISTRATION_V14.md` before the held-out run.",
           "- VZCrash test split for V16: `int(sha256('r5|' + event_id), 16) mod 2` (HALF0 development and detection, HALF1 held-out for L2); recomputed here: HALF0 {} events, HALF1 {} events, equal to `results/tables/r5_split_hashes.json`. That file was committed together with the held-out results, not before them; the rule was in the preregistration before any run.".format(cur["n_half0"], cur["n_half1"]),
           "- FARS: development years 2019 to 2021, held-out year 2022 (fixed in V16 section 15.2).",
           "", "## Code and derived data", "", "Code: Apache-2.0 (`LICENSE`, `NOTICE`). Derived files that contain VZCrash-derived values keep CC BY-NC 4.0 with attribution. NHTSA-derived and FARS-derived tables are public-domain inputs; LoED, the sniffer set, GeoNames, UCI HAR and the SisFall copy are CC BY 4.0 and are cited with their DOIs.",
           "", "SisFall note: the Zenodo record 22212281 lists no creators and was deposited on 2026-08-31. The original dataset is Sucerquia, López and Vargas-Bonilla, Sensors 17(1):198, 2017. The licence is the one stated on the Zenodo record; the author should confirm it with the original source before submission (listed in `paper/PLACEHOLDERS.md`)."]
    (ROOT / "docs" / "05_data_code" / "DATA_SOURCES.md").write_text("\n".join(doc) + "\n", encoding="utf-8")
    print("\n".join(out))
    print("all ok:", allok, cur["n_half0"], cur["n_half1"])


if __name__ == "__main__":
    main()
