"""Claim audit of the final run's Parts A and B (writes docs/04_audits/ROUND3_CLAIM_AUDIT.md).

Checks: (1) every result key that existed at tag redesign-v1.1 is unchanged; (2) new keys carry the prefixes lit. or r3. and a label from the allowed set, and none is a hardware label;
(3) NOT_RUN entries state a reason; (4) data/hardware is untouched; (5) the wording rules hold in the generated documents; (6) every verdict in the decision table equals the stored verdict key;
(7) the preregistration file was committed before the first commit of any T1 to T3 code. Run after r3_docs.
"""
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OK = {"MEASURED_SOFTWARE", "SIMULATED", "SIMULATED_HW_FORMAT", "TRACE_DRIVEN", "FORMAL", "ANALYTICAL", "EMULATED", "NOT_RUN"}


def git(*a: str) -> str:
    return subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True, encoding="utf-8").stdout


def main() -> None:
    old = {e["name"]: e for e in json.loads(git("show", "redesign-v1.1:results/results.json"))}
    new = {e["name"]: e for e in json.loads((ROOT / "results" / "results.json").read_text(encoding="utf-8"))}
    changed = [k for k, e in old.items() if k not in new or new[k] != e]
    added = [k for k in new if k not in old]
    bad_prefix = [k for k in added if not (k.startswith("lit.") or k.startswith("r3."))]
    bad_label = [k for k in added if new[k]["origin"] not in OK]
    no_reason = [k for k in added if (new[k]["value"] == "NOT_RUN" or new[k]["origin"] == "NOT_RUN") and not str(new[k].get("notes", "")).strip()]
    hw = git("diff", "--stat", "redesign-v1.1", "--", "data/hardware").strip()
    log = git("log", "--format=%H %s", "--reverse", "redesign-v1.1..HEAD").splitlines()
    idx_pre = next((i for i, ln in enumerate(log) if "PREREGISTRATION_V14" in ln), None)
    idx_code = next((i for i, ln in enumerate(log) if ln.split(" ", 1)[1].startswith("T1 code")), None)
    prereg_first = idx_pre is not None and idx_code is not None and idx_pre < idx_code
    style = subprocess.run(["python", "scripts/doc_style_check.py"], cwd=ROOT, capture_output=True, text=True).stdout.strip().splitlines()[-1]
    dec = (ROOT / "docs" / "03_results" / "ROUND3_DECISION_TABLE.md").read_text(encoding="utf-8")
    mism = []
    for key, name in (("r3.holm.ht1b.verdict", "H-T1b"), ("r3.holm.ht1c.verdict", "H-T1c"), ("r3.holm.ht3a.verdict", "H-T3a"), ("r3.holm.ht3b.verdict", "H-T3b")):
        row = next((ln for ln in dec.splitlines() if ln.startswith(f"| {name} ")), "")
        if new[key]["value"] not in row:
            mism.append(name)
    by_prefix = {p: sum(1 for k in added if k.startswith(p)) for p in ("lit.", "r3.")}
    L = ["# Claim audit of the final run, Parts A and B", "",
         "Generated by `scripts/r3_audit.py` after `crashguard.r3_docs`. Branch `final`, compared with tag `redesign-v1.1`.", "",
         "| Check | Result |", "|---|---|",
         f"| Result keys of `redesign-v1.1` unchanged | {len(old) - len(changed)} of {len(old)} unchanged; changed or missing: {len(changed)} |",
         f"| New keys | {len(added)} ({by_prefix['lit.']} with prefix lit., {by_prefix['r3.']} with prefix r3.); other prefixes: {len(bad_prefix)} |",
         f"| New keys with a label outside the allowed set (no hardware label) | {len(bad_label)} |",
         f"| New NOT_RUN keys without a reason | {len(no_reason)} |",
         f"| `data/hardware` changed since the tag | {'no' if not hw else hw} |",
         f"| Preregistration V14 committed before the T1 code | {'yes' if prereg_first else 'NO'} |",
         f"| Wording check (`doc_style_check.py`) | {style} |",
         f"| Decision-table verdicts equal the stored verdict keys (H-T1b, H-T1c, H-T3a, H-T3b) | {'yes' if not mism else 'MISMATCH ' + ', '.join(mism)} |",
         "| Push, upload, e-mail, API-key request | none made; the OpenAlex notice asking for a key and an e-mail address was ignored |", ""]
    ok = not changed and not bad_prefix and not bad_label and not no_reason and not hw and prereg_first and not mism
    L.append(f"**Overall: {'all checks pass' if ok else 'a check failed (see the table)'}.**")
    if changed:
        L += ["", "Changed or missing keys: " + ", ".join(changed[:20])]
    out = ROOT / "docs" / "04_audits" / "ROUND3_CLAIM_AUDIT.md"
    out.write_text("# Claim audit of the final run, Parts A and B\n\n" + "\n".join(L[2:]) + "\n", encoding="utf-8")
    print(re.sub(r"\n+", "\n", "\n".join(L[3:])))


if __name__ == "__main__":
    main()
