"""V3.2: rerun one R3 cell at SF7, one at SF9 and one D1 cell in the patched ns-3 build; compare every run file with the stored one.

    PYTHONPATH=src python scripts/vf_ns3_rerun.py

Runs go to data/processed/vf_ns3_out (git-ignored). A run file is the application's text output; it is identical when the
patched build is the one that produced the stored file (the application is deterministic for a given seed and arguments).
Writes docs/03_results/VF_NS3_RERUN.md and keys vf.ns3.* in results.json.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
from pathlib import Path

from crashguard import pp_r3_ns3 as P
from crashguard import rd_firmware as F
from crashguard import rd_x13 as X
from crashguard.results import record_many

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data" / "processed" / "vf_ns3_out"
JOBS = ROOT / "data" / "processed" / "vf_ns3_jobs"
SEEDS = 20  # of the 60 per cell; the runs are independent, so 20 are enough for a check and take seconds
HOURS = 20


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def run_jobs(jobs: list[tuple[str, str]], workers: int = 8) -> None:
    JOBS.mkdir(parents=True, exist_ok=True)
    script = P.JOB_SCRIPT.replace("{NS}", P.NS_BIN)
    (JOBS / "job.sh").write_bytes(script.encode("utf-8"))
    procs = []
    for k in range(workers):
        ch = jobs[k::workers]
        if not ch:
            continue
        jf = JOBS / f"jobs_{k}.txt"
        jf.write_bytes(("\n".join(f"{o}|{a}" for o, a in ch) + "\n").encode("utf-8"))
        procs.append(subprocess.Popen(["wsl", "-d", "Ubuntu", "--", "bash", F.wsl_path(JOBS / "job.sh"), F.wsl_path(jf)]))
    for p in procs:
        p.wait()


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    P.make_events()
    rows, jobs, pairs = [], [], []
    # R3 cells: SF7 and SF9, calibration setting, extra loss 0.3, both policies
    for sf in (7, 9):
        for pol in P.POLS:
            for s in range(1, SEEDS + 1):
                stored = P.fname(sf, "calib", 0.3, pol, s)
                new = OUT / f"r3_{stored.name}"
                args = f"--n={P.N_VEH} --sf={sf} --p=0.3 --radius={P.RADIUS} --rate={P.RATE} --duty=0.01 --seed={s} --policy={pol} --events={F.wsl_path(P.EVENTS)} --sensShipped=0"
                jobs.append((F.wsl_path(new), args))
                pairs.append((f"R3 SF{sf} calib p0.3 {pol}", stored, new))
    # D1 cell: first S-X cell (SF9), policy d1, hours 0 to HOURS - 1
    c = X.sx_cells()[0]
    tab = F.wsl_path(X.OUT / "rd_fw_d1_sf9.bin")
    for h in range(HOURS):
        stored = X.OUT / "xsim_out" / f"{c['name']}__d1__{h}.txt"
        new = OUT / f"d1_{stored.name}"
        args = f"--n={c['n']} --sf=9 --p={c['p']} --duty={c['duty']} --b={c['b']} --seed={h + 1} --policy=d1 --table={tab}"
        jobs.append((F.wsl_path(new), args))
        pairs.append((f"D1 {c['name']}", stored, new))
    for _, _, new in pairs:
        new.unlink(missing_ok=True)
    run_jobs(jobs)
    summ: dict = {}
    for label, stored, new in pairs:
        same = new.exists() and stored.exists() and new.read_bytes() == stored.read_bytes()
        s = summ.setdefault(label, dict(n=0, identical=0, stored_empty=0, new_empty=0))
        s["n"] += 1
        s["identical"] += bool(same)
        s["stored_empty"] += int(stored.exists() and stored.stat().st_size == 0)
        s["new_empty"] += int(new.exists() and new.stat().st_size == 0)
    tab_hash = sha(X.OUT / "rd_fw_d1_sf9.bin")
    for label, s in summ.items():
        rows.append(f"| {label} | {s['n']} | {s['identical']} | {s['stored_empty']} | {s['new_empty']} |")
    binhash = subprocess.run(["wsl", "-d", "Ubuntu", "--", "bash", "-c", "cd ~/ns3work/ns-3-dev && sha256sum build/scratch/ns3.48-xsim_alert-optimized build/lib/libns3.48-lorawan-optimized.so | cut -c1-64"], capture_output=True, text=True).stdout.split()
    lines = ["# ns-3 rerun against the stored runs (V3.2)", "",
             "<!-- header:start -->", "| Field | Value |", "|---|---|", "| Status | current |", "| Date | 2026-11-15 |", "| Owner | Mritula S |",
             "| Scope | Rerun of R3 cells (SF7, SF9) and one D1 cell in the patched ns-3 build, compared run by run with the stored output files (generated by scripts/vf_ns3_rerun.py). |",
             "| Evidence labels used | SIMULATED |", "| Abbreviations | SF = LoRa spreading factor; ns-3 = network simulator 3; R3 = two-stage alert; D1 = loss-adaptive retry table |",
             "<!-- header:end -->", "",
             f"Build: `ns3.48-xsim_alert-optimized` SHA-256 {binhash[0] if binhash else '?'}; `libns3.48-lorawan-optimized.so` SHA-256 {binhash[1] if len(binhash) > 1 else '?'}; D1 table `rd_fw_d1_sf9.bin` SHA-256 {tab_hash}. Patch: `xsim/ns3/patches/lorawan-v0.3.7-2-ge45b4af-local.patch` (includes the RX2 sub-band null-pointer fix).", "",
             "Each run is compared byte for byte with the stored file (the application is deterministic for a given seed and arguments). 'Stored empty' means the stored run crashed inside the module (the known 0.2% of runs).", "",
             "| Cell | Runs | Identical to stored | Stored empty | Rerun empty |", "|---|---|---|---|---|"] + rows + [""]
    (ROOT / "docs" / "03_results" / "VF_NS3_RERUN.md").write_text("\n".join(lines), encoding="utf-8")
    ent = []
    for label, s in summ.items():
        key = label.replace(" ", "_").replace(".", "")
        ent.append(dict(name=f"vf.ns3.{key}.identical", value=s["identical"], unit="runs", origin="SIMULATED", source_file="scripts/vf_ns3_rerun.py", notes=f"of {s['n']} runs rerun in the patched ns-3 build"))
        ent.append(dict(name=f"vf.ns3.{key}.runs", value=s["n"], unit="runs", origin="SIMULATED", source_file="scripts/vf_ns3_rerun.py"))
    record_many(ent, purge_prefixes=("vf.ns3.",))
    print(json.dumps(summ, indent=1))


if __name__ == "__main__":
    main()
