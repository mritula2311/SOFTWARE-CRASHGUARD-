"""Writes docs/03_results/CODE_VERIFICATION.md from the tests under tests/redesign (pass counts by file, from a pytest run), the mutation table and the entries under ``rd.cv.*``.

Items that are not done yet are written as NOT_RUN with the reason. Run after the tests and the mutation script:
    python scripts/rd_cv_doc.py
"""
from __future__ import annotations

import csv
import json
import os
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HDR = """# Code verification of the redesign modules

<!-- header:start -->
| Field | Value |
|---|---|
| Status | current |
| Date | 2026-11-14 |
| Owner | Mritula S |
| Scope | Unit, property, invariant, differential, mutation, review and known-answer results for the redesign policy, simulator hooks and security code (generated). |
| Evidence labels used | ANALYTICAL, NOT_RUN |
| Abbreviations | ACK = acknowledgement frame; CV = code verification; DP = dynamic programme; HMAC = hash-based message authentication code |
<!-- header:end -->

Generated by `python scripts/rd_cv_doc.py`. The checks of section 7 of `docs/02_preregistration/PREREGISTRATION_V12.md`; a module must pass them before it touches a fresh grid. Tests live in `tests/redesign/`.
"""


REVIEW = [
    (1, "a demoted D1 alert stopped after one more try instead of the class limit (8 or 12)", "MAJOR", "fixed in `world_sim.py`"),
    (2, "a simulated round is flash plus alert, the table plans one alert per attempt", "MAJOR", "disclosed (V12 addendum A, 5a); not changed"),
    (3, "event bootstrap ignores correlation within a simulated hour", "MAJOR", "verdicts now use the more conservative of the event and the hour-cluster bootstrap (addendum A, 1)"),
    (4, "H-D2c model run with smaller bounds than preregistered", "MAJOR", "2 vehicles now at the preregistered bounds; 3 vehicles at reduced bounds, stated (addendum A, 3)"),
    (5, "the stolen-gateway-key limit case could never be flagged", "MAJOR", "fixed in `rd_d2_model.py`"),
    (6, "two model properties hold by construction; the attacker flood needs per-vehicle keys", "MINOR", "disclosed in the model docstring and addendum A, 3"),
    (7, "criterion form (p below 0.05 and point at least 0.05) differs from the two-sided interval", "MINOR", "stated in addendum A, 2"),
    (8, "a defer could push a retry past the class deadline", "MINOR", "fixed (capped at deadline minus one round)"),
    (9, "the Beta mean and the table both count the current failures", "MINOR", "disclosed (5b)"),
    (10, "table caps NB_MAX and J_MAX have no stated origin and bind", "MINOR", "disclosed (5c)"),
    (11, "the cluster ACK lists only the 24 most recent vehicles", "MINOR", "disclosed (5d)"),
    (12, "a demoted alert kept the raised SF", "MINOR", "fixed"),
    (13, "float32 delays at the deadline boundary", "MINOR", "fixed (float64)"),
    (14, "gate computed before the current frame is counted; the initial attempt uses only the table SF", "NOTE", "noted; unchanged"),
    (15, "Beta success counted once per alert, failures per round", "NOTE", "noted; unchanged"),
    (16, "the simulator does not call `ClusterAckVerifier` or `NodeState`", "NOTE", "covered by the D6 differential test (session 2) (5e)"),
    (17, "b = 1 cells contain a one-vehicle burst cell; D2 equals D1 there only because thr is at least 2", "NOTE", "assertion added (thr of at least 2)"),
    (18, "constants without a stated origin", "NOTE", "listed (5g) and in `ASSUMPTIONS.md`"),
    (19, "DEV and FRESH-A share the finite class pool", "NOTE", "disclosed (5f)"),
    (20, "freeze hashed too few modules", "NOTE", "extended (addendum A, 6)"),
]


def main() -> None:
    xml = ROOT / "build" / "rd_tests.xml"
    xml.parent.mkdir(exist_ok=True)
    env = {**os.environ, "PYTHONPATH": str(ROOT / "src")}
    subprocess.run([sys.executable, "-m", "pytest", "tests/redesign", "-q", "-p", "no:cacheprovider", f"--junitxml={xml}"], cwd=ROOT, env=env, capture_output=True, text=True)
    by_file: dict = defaultdict(lambda: [0, 0, 0])
    for tc in ET.parse(xml).getroot().iter("testcase"):
        f = tc.get("classname", "").split(".")[-2] if "." in tc.get("classname", "") else tc.get("classname", "")
        rec = by_file[f]
        rec[0] += 1
        if tc.find("failure") is not None or tc.find("error") is not None:
            rec[1] += 1
        if tc.find("skipped") is not None:
            rec[2] += 1
    L = [HDR, "## 1 to 3 and 7: tests (pass counts from the last run)\n", "| Test file | Tests | Failed | Skipped | Covers |", "|---|---|---|---|---|"]
    cover = {"test_rd_policy": "CV1 unit tests with hand-computed time on air (24, 40, 97 bytes, SF7 to SF12 samples), Beta updates, deadline arithmetic, bins, cluster-ACK length and parsing; CV2 property tests (no retry after the deadline, airtime never above the budget, monotone table, tampered or replayed frame never accepted, a defer never a stop)",
             "test_rd_security": "CV1 and CV2 for the node-side ACK check (matching alert only; tampering never accepted)",
             "test_rd_sim": "CV3 run-time invariants (no negative time, no send in a blackout, delivered implies sent, events conserved, ACK only for a received alert) with D1 and D2 on; CV7 known answers (a UA-SCT cell, an OS-DR cell, the R3 result) with the changed simulator"}
    tot = [0, 0, 0]
    for f, (n, bad, sk) in sorted(by_file.items()):
        L.append(f"| {f} | {n} | {bad} | {sk} | {cover.get(f, '')} |")
        tot = [tot[0] + n, tot[1] + bad, tot[2] + sk]
    L.append(f"| **all** | {tot[0]} | {tot[1]} | {tot[2]} | |")
    mut = ROOT / "results/tables/rd_mutation.csv"
    L.append("\n## 5: mutation testing (31 hand-written mutants; mutmut does not run on Windows)\n")
    if mut.exists():
        rows = list(csv.DictReader(mut.open(encoding="utf-8")))
        k = sum(r["status"] == "KILLED" for r in rows)
        L.append(f"Mutants killed: **{k} of {len(rows)}** ({k / len(rows):.0%}); the threshold is 80%. Script `scripts/rd_mutation.py`. The initial run killed 27 of 31 (87%); the four survivors showed missing tests (table dependence on failed attempts, the crowd term, the cluster-ACK count check, the node-side ACK counter check), which were added, and the rerun is the number above.\n")
        L.append("| Id | File | Mutant | Result |\n|---|---|---|---|")
        for r in rows:
            L.append(f"| {r['id']} | {r['file'].split('/')[-1]} | {r['description']} | {r['status']} |")
    else:
        L.append("NOT_RUN: `scripts/rd_mutation.py` has not been run.")
    res = {e["name"]: e for e in json.loads((ROOT / "results/results.json").read_text(encoding="utf-8")) if e["name"].startswith("rd.cv.")}
    L.append("\n## 4: differential test (simulator policy against the firmware-path implementation)\n")
    d = res.get("rd.cv.differential.mismatches")
    L.append(f"{d['value']} mismatches over {res['rd.cv.differential.traces']['value']} random traces." if d else "NOT_RUN: the firmware-path implementation (D6) is built in session 2; the test is run then.")
    L.append("\n## 6: independent review pass\n")
    L.append("A reviewer in a fresh context (a subagent told not to read results, tables or DEV logs) read the policy, simulator hooks, evaluation code and bounded model against `docs/02_preregistration/PREREGISTRATION_V12.md` before the freeze. It reported no blocker and no use of held-out data in the evaluation path (the old held-out logs are read only by `rd_d0.py`, the declared DIAGNOSIS step). 20 findings and what was done:\n")
    L.append("| # | Finding (short) | Severity | Disposition |\n|---|---|---|---|")
    for n_, f_, sv_, d_ in REVIEW:
        L.append(f"| {n_} | {f_} | {sv_} | {d_} |")
    L.append("\n## Findings of the checks so far\n")
    L.append("- The property test of table monotonicity found 107 violations in the raw dynamic-programme output; a monotone projection was added (`D1Table._monotone`) and the test passes.")
    L.append("- The invariant check found a variable shadowing bug in the initial version of the D2 hook (`active` hid the list of transmissions) and, in the initial D2 test, a cluster mode that triggered on one vehicle's repeated frames; the hook now counts distinct vehicles.")
    L.append("- The invariant `events conserved` needed the event that ended the run to be kept in the queue so that transmissions in flight are counted.")
    (ROOT / "docs/03_results/CODE_VERIFICATION.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("written", tot)


if __name__ == "__main__":
    main()
