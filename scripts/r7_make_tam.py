"""Derive the pseudonymous Tamarin model (formal/r7_alert_pseudo_fresh_bootctr.spthy) from formal/crash_alert_fresh_bootctr.spthy.

The alert frame carries the pseudonym p = pseud(kdf(km, v), f) of the alert id f = <b, e, n> instead of the vehicle and the id; the tag is mac(kdf(km, v), <'A', p, f>) (the base recovers f from its window entry and
recomputes it). The persistent fact !Win(p, v, f) stands for the precomputed window entry (every pseudonym the vehicle sends is in the base's window: resynchronisation succeeds). The lemmas and restrictions are unchanged.
"""
from pathlib import Path

R = Path(__file__).resolve().parents[1] / "formal"
t = (R / "crash_alert_fresh_bootctr.spthy").read_text(encoding="utf-8")


def pseud(f: str) -> str:
    return f"pseud(kdf(km, $v), {f})"


def send(f: str) -> tuple[str, str]:
    old = f"Out(<'ALERT', $v, {f}, mac(kdf(km, $v), <'A', $v, {f}>)>) ]"
    new = f"Out(<'ALERT', {pseud(f)}, mac(kdf(km, $v), <'A', {pseud(f)}, {f}>)>), !Win({pseud(f)}, $v, {f}) ]"
    return old, new


for f in ("<b, e, n>", "<b, e, m>", "<'B', be, n>", "<'B', be, m>"):
    o, n = send(f)
    assert o in t, f
    t = t.replace(o, n)


def base(f: str) -> tuple[str, str]:
    old = f"In(<'ALERT', $v, {f}, mac(kdf(km, $v), <'A', $v, {f}>)>) ]"
    new = f"In(<'ALERT', p, mac(kdf(km, $v), <'A', p, {f}>)>), !Win(p, $v, {f}) ]"
    return old, new


for f in ("<b, e, n>", "<b, ep, n>", "<'B', be, n>"):
    o, n = base(f)
    assert o in t, f
    t = t.replace(o, n)
t = t.replace("functions: kdf/2, mac/2", "functions: kdf/2, mac/2, pseud/2")
t = t.replace("theory CrashAlertFreshBootCtr", "theory CrashAlertPseudoFreshBootCtr")
t = "/* Round 7 B2.2: the boot-counter freshness model of round 3 with the pseudonymous id (generated by scripts/r7_make_tam.py from crash_alert_fresh_bootctr.spthy; lemmas and restrictions unchanged). */\n" + t
(R / "r7_alert_pseudo_fresh_bootctr.spthy").write_text(t, encoding="utf-8")
print("written")
