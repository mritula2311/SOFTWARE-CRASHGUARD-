def main() -> None:
    n_neg = sum(float(R[f"r6.r1.ns3.sf{sf}.{st}.p{p}.extra_air_ratio"]) < 0 for sf, st, p in CELLS)
    max_dd = max(abs(float(R[f"r6.r1.ns3.sf{sf}.{st}.p{p}.delivery_diff"])) for sf, st, p in CELLS)
    max_drop = max(float(R[f"r6.r1.ns3.sf{sf}.{st}.p{p}.dropped_share"]) for sf, st, p in CELLS)
    L = [HEAD]
    L.append("## 1. Result in one paragraph\n")
    L.append(
        f"In ns-3 the micro-confirm scheme sends less airtime than R3 in every one of the 16 cells (between {min(float(R[f'r6.r1.ns3.sf{sf}.{st}.p{p}.air_over_r3']) for sf in (7, 9) for st in ('calib', 'shipped') for p in ('0', '0.1', '0.3', '0.6')):.2f} and "
        f"{max(float(R[f'r6.r1.ns3.sf{sf}.{st}.p{p}.air_over_r3']) for sf in (7, 9) for st in ('calib', 'shipped') for p in ('0', '0.1', '0.3', '0.6')):.2f} of R3's airtime) and its delivery is within {max_dd:.4f} of R3's in every cell. "
        f"H-R6-1a (SF9 extra airtime at most 0.40) and H-R6-1b (delivery not lower than R3 by more than 1 point) meet their criteria as defined. Two limits apply. One: H-R6-1a is close to automatic, because the extra airtime against the single-stage alert is negative in {n_neg} of the 16 cells, as the micro-confirm replaces the 97-byte confirm, so the table below also gives the airtime against R3 and per delivered alert. "
        "The other: the trace part of H-R6-1b is zero by construction (loss depends on the frame index, not on the frame length), so it adds nothing to the ns-3 evidence. The formal part (H-R6-1c) is in section 4.\n"
    )
    L.append("## 2. ns-3 cells (60 seeds, 60 vehicles, ADR off; `r6m` against the stored `r3s` and `r3t` runs of the same seeds)\n")
    L.append("| SF | Setting | Loss p | Extra airtime vs single-stage (upper 95%) | Airtime over R3 | Per delivered alert over R3 | Delivery R3 | Delivery micro | Difference (lower 95%) | Events dropped |")
    L.append("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for sf in (7, 9):
        for st in ("calib", "shipped"):
            for p in ("0", "0.1", "0.3", "0.6"):
                c = f"r6.r1.ns3.sf{sf}.{st}.p{p}"
                L.append(
                    f"| {sf} | {st} | {p} | {float(R[c + '.extra_air_ratio']):+.3f} ({float(R[c + '.extra_air_ratio_hi']):+.3f}) | {f(c + '.air_over_r3')} | {f(c + '.air_per_delivered_over_r3')} | {f(c + '.delivery_r3', 4)} | "
                    f"{f(c + '.delivery_micro', 4)} | {float(R[c + '.delivery_diff']):+.4f} ({float(R[c + '.delivery_diff_lo']):+.4f}) | {f(c + '.dropped_share', 3)} |"
                )
    L.append(
        "\nDefinitions: extra airtime is the micro scheme's total transmit airtime over the single-stage total, minus one (R3 definition); delivery is a crash event whose critical content reached the base within 10 s; "
        f"intervals are cluster bootstraps over runs (2,000 resamples, seed 42). No cell dropped more than {max_drop:.1%} of events and no run was lost. At SF9 and loss 0.6 the extra airtime is +0.03, still below 0.40.\n"
    )
    L.append("## 3. Trace groups (LoED half 0, 300 start points per device)\n")
    L.append("| Group | Devices | Delivery difference (lower 95%) | Airtime over R3, 13-byte frame | Airtime over R3, 7-byte frame |")
    L.append("|---|---:|---:|---:|---:|")
    for g in "LMH":
        c = f"r6.r1.trace.{g}"
        L.append(f"| {g} | {int(R[c + '.n_devices'])} | {float(R[c + '.delivery_diff']):+.3f} ({float(R[c + '.delivery_diff_lo']):+.3f}) | {f(c + '.air_over_r3')} | {f(c + '.air_over_r3_7byte')} |")
    L.append("\nThe difference is zero because a replayed attempt sees the reception state of its frame index and the frame length does not enter. The airtime columns are informative; delivery is not.\n")
    L.append("## 4. Formal status (H-R6-1c) and limits\n")
    L.append(
        "The formal part is reported in `docs/03_results/ROUND6_RESULTS.md` (ProVerif and Tamarin models and the control model; outputs in `formal/out/r6/`). The ns-3 frame has 13 bytes (the smallest frame of the LoRaWAN module) and the design frame has 7; at SF7 a 13-byte and a 14-byte frame have the same time on air, so the ns-3 micro frame saves airtime only against the 97-byte confirm. "
        "The micro-confirm gives up the delta-V, peak, switch bits and telemetry of the full confirm (a limit, not measured here). The pending-table lifetime (10, 30, 60 s) made no difference in development, because the confirm is always sent within 10 s of the acknowledged flash.\n"
    )
    L.append("## 5. Development, code checks\n")
    L.append("| Iteration | Pending lifetime (s) | Worst-cell delivery difference | Largest extra airtime |")
    L.append("|---|---:|---:|---:|")
    for e in DEV:
        L.append(f"| {e['iteration']} | {e['pend_s']:g} | {e['worst_cell_delivery_diff']:+.4f} | {e['max_ratio_s']:+.3f} |")
    L.append(
        "\nIterations 1 to 3 ran on an earlier build of the policy (before the review fix of the frame size at expiry); iteration 4 ran on the frozen build. 21 tests in `tests/test_r6_micro.py` (including a deterministic ns-3 check), 35 mutants all killed "
        "(`results/tables/r6_mutation_r1.csv`), a known-answer test that reproduces the stored P1 cell, and a fresh-context review whose findings were applied before the freeze (DECISIONS.md, 2026-11-16). "
        "The earlier ns-3 policies give byte-identical output with the new binary (42 runs, 0 differences, `scripts/r5_ns3_identity.sh`). The held-out seeds 1 to 60 were used by R3 for another question and are held-out for this one only.\n"
    )
    (ROOT / "docs" / "03_results" / "ROUND6_R1_MICRO.md").write_text("\n".join(L), encoding="utf-8")


if __name__ == "__main__":
    main()
